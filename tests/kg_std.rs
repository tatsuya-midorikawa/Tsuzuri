//! G27 Phase 4 (D-60): the knowledge graph of the standard library, in the compiler's cache or in
//! memory, and the view that reads a project's graph first and std's after it.

use std::path::{Path, PathBuf};
use std::process::{Command, Output};
use std::sync::Arc;
use std::sync::atomic::{AtomicUsize, Ordering};

use tsuzuri::kg::store::{KgView, StdSource};

fn temporary(label: &str) -> PathBuf {
    static COUNTER: AtomicUsize = AtomicUsize::new(0);
    let dir = std::env::temp_dir().join(format!(
        "tsuzuri-kg-std-{label}-{}-{}",
        std::process::id(),
        COUNTER.fetch_add(1, Ordering::Relaxed)
    ));
    let _ = std::fs::remove_dir_all(&dir);
    std::fs::create_dir_all(&dir).unwrap();
    dir
}

fn tsuzuri(cache: &Path, arguments: &[&str]) -> Output {
    Command::new(env!("CARGO_BIN_EXE_tsuzuri"))
        .args(arguments)
        .env("TSUZURI_CACHE_DIR", cache)
        .env_remove("TSUZURI_KG")
        .env_remove("TSUZURI_KG_DIR")
        .output()
        .unwrap()
}

fn stdout(output: &Output) -> String {
    String::from_utf8_lossy(&output.stdout).into_owned()
}

#[test]
fn std_kg_is_built_once_and_old_generations_are_removed() {
    let cache = temporary("generations");
    let output = tsuzuri(&cache, &["kg", "build", "--std"]);
    assert!(
        output.status.success(),
        "{}",
        String::from_utf8_lossy(&output.stderr)
    );
    let text = stdout(&output);
    assert!(text.starts_with("kg: wrote "), "{text}");
    let root = cache.join("kg-std");
    let generations: Vec<PathBuf> = std::fs::read_dir(&root)
        .unwrap()
        .map(|entry| entry.unwrap().path())
        .collect();
    assert_eq!(generations.len(), 1);
    let current = generations[0].clone();
    assert_eq!(current.file_name().unwrap().len(), 16);
    let manifest = std::fs::read_to_string(current.join("manifest.json")).unwrap();
    assert!(manifest.contains("\"project\": \"std\""));
    let nodes = std::fs::read_to_string(current.join("nodes.jsonl")).unwrap();
    assert!(nodes.contains("{\"id\":\"Array.map\",\"kind\":\"def\",\"module\":\"Array\""));
    assert!(
        nodes
            .lines()
            .all(|line| line.contains("\"origin\":\"std\""))
    );
    let again = tsuzuri(&cache, &["kg", "build", "--std"]);
    assert!(
        stdout(&again).starts_with("kg: up to date ("),
        "{}",
        stdout(&again)
    );
    // Four older generations of other compilers: only the three newest graphs stay.
    for (index, age) in [(0, 400), (1, 300), (2, 200), (3, 100)] {
        let old = root.join(format!("{index:016x}"));
        std::fs::create_dir_all(&old).unwrap();
        let marker = old.join(".tsuzuri-kg");
        std::fs::write(&marker, "generated by tsuzuri kg\nstamp 00\n").unwrap();
        let time = std::time::SystemTime::now() - std::time::Duration::from_secs(age);
        std::fs::File::options()
            .write(true)
            .open(&marker)
            .unwrap()
            .set_modified(time)
            .unwrap();
    }
    assert!(
        tsuzuri(&cache, &["kg", "build", "--std", "--force"])
            .status
            .success()
    );
    let mut kept: Vec<String> = std::fs::read_dir(&root)
        .unwrap()
        .map(|entry| entry.unwrap().file_name().to_string_lossy().into_owned())
        .collect();
    kept.sort();
    let mut expected = vec![
        current.file_name().unwrap().to_string_lossy().into_owned(),
        format!("{:016x}", 2),
        format!("{:016x}", 3),
    ];
    expected.sort();
    assert_eq!(kept, expected);
    assert!(tsuzuri(&cache, &["kg", "clean", "--std"]).status.success());
    assert!(!root.exists());
}

#[test]
fn std_flag_takes_no_path() {
    let cache = temporary("flags");
    let output = tsuzuri(&cache, &["kg", "build", "--std", "."]);
    assert_eq!(output.status.code(), Some(2));
}

/// The (path, size, modification time) of every file below `dir`.
fn snapshot(dir: &Path) -> Vec<(PathBuf, u64, std::time::SystemTime)> {
    let mut found = Vec::new();
    let mut pending = vec![dir.to_owned()];
    while let Some(at) = pending.pop() {
        let Ok(entries) = std::fs::read_dir(&at) else {
            continue;
        };
        for entry in entries {
            let path = entry.unwrap().path();
            let metadata = std::fs::metadata(&path).unwrap();
            if metadata.is_dir() {
                pending.push(path);
            } else {
                found.push((path, metadata.len(), metadata.modified().unwrap()));
            }
        }
    }
    found.sort();
    found
}

#[test]
fn memory_mode_writes_nothing_and_the_project_comes_first() {
    let cache = std::env::var_os("TSUZURI_CACHE_DIR")
        .map(PathBuf::from)
        .unwrap_or_else(|| std::env::temp_dir().join("tsuzuri-no-cache"));
    let before = snapshot(&cache.join("kg-std"));
    let project = tsuzuri::kg::collect_sources(&[(
        "Main.tz",
        "def total :: [i64] -> i64 = \\xs -> Array.fold (\\a b -> a + b) 0 xs\n",
    )])
    .unwrap();
    let mut files = tsuzuri::kg::emit::emit(&project).unwrap();
    files.put("diag.jsonl", Vec::new());
    let manifest = tsuzuri::kg::manifest::Manifest {
        schema: "tz-kg/1".into(),
        compiler: "tsuzuri 0.1.0".into(),
        edition: "2027".into(),
        project: "app".into(),
        version: None,
        complete: true,
        source_hash: String::new(),
        counts: Vec::new(),
        modules: Vec::new(),
        files: files
            .0
            .keys()
            .map(|path| (path.clone(), String::new()))
            .collect(),
    };
    let data = tsuzuri::kg::store::KgData::from_parts(&manifest, &files).unwrap();
    let view = KgView::new(Some(Arc::new(data)), StdSource::Memory);
    assert_eq!(view.node("Main.total").unwrap().origin, "project");
    let fold = view
        .node("Array.fold")
        .expect("the std graph has Array.fold");
    assert_eq!(
        (fold.origin.as_str(), fold.module.as_str()),
        ("std", "Array")
    );
    // A call to std from the project reaches a std node through the project's edge (edition 2027
    // resolves `Array.fold` to its borrowing or owning twin).
    let targets: Vec<String> = view
        .edges_from("calls", "Main.total")
        .iter()
        .map(|edge| edge.to.clone())
        .collect();
    let target = targets
        .iter()
        .find(|to| to.starts_with("Array.fold"))
        .unwrap_or_else(|| panic!("{targets:?}"));
    assert_eq!(view.node(target).unwrap().origin, "std");
    assert_eq!(snapshot(&cache.join("kg-std")), before);
    let without = KgView::new(None, StdSource::None);
    assert!(without.node("Array.fold").is_none());
}
