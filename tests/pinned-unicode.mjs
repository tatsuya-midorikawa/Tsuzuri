// The V8 expectations of the `regex` and `unicode` suites of tests/features.mjs (G38). V8 computes them with the
// Unicode version of the Node that runs it, while std's tables are pinned to UNICODE_VERSION of
// scripts/generate-unicode.mjs. So a Node with std's version writes them to tests/regex-v8.mjs and
// tests/unicode-v8.mjs, the suites read them there on any Node, and a Node with std's version also recomputes them
// and compares. The cases modules build their cases with `build(v8)`, which returns the cases of the suite in order
// and gives each one whose expectation V8 computes as `v8(name, args, compute)`.
import assert from "node:assert/strict";
import { UNICODE_VERSION } from "../scripts/generate-unicode.mjs";

/// std's Unicode version as `process.versions.unicode` writes it (`17.0`).
export const PINNED_UNICODE = UNICODE_VERSION.split(".").slice(0, 2).join(".");
/// Whether V8 in this Node has std's Unicode version.
export const pinnedNode = process.versions.unicode === PINNED_UNICODE;

/// For the commands that write V8 expectations: unless this Node has std's Unicode version, exits with status 1
/// before anything is written.
export function requirePinnedNode() {
  if (pinnedNode) return;
  console.error(`the Unicode of this Node (${process.versions.unicode}) is not std's (${PINNED_UNICODE}); use a Node with Unicode ${PINNED_UNICODE}`);
  process.exit(1);
}

/// The cases of `build` whose expectations V8 computes, computed, in order.
export function v8CasesOf(build) {
  const computed = [];
  build((name, args, compute) => {
    const item = [name, args, compute()];
    computed.push(item);
    return item;
  });
  return computed;
}

/// The cases of `build` with the V8 expectations of `references`, the committed `cases` of `file` that `command`
/// writes. A Node with std's Unicode version first checks them against V8 (`v8Cases`); another Node prints one line
/// and uses them as they are. Either way each reference must be for the export and arguments of its place.
export function casesWithReferences(build, references, file, command, v8Cases) {
  if (pinnedNode) {
    const computed = v8Cases();
    for (let index = 0; index < Math.max(references.length, computed.length); index++) {
      assert.deepEqual(references[index], computed[index], `${file} differs from V8 at case ${index}; if the cases changed, run ${command}`);
    }
    console.log(`${file}: the ${references.length} V8 expectations equal V8's with Unicode ${PINNED_UNICODE}`);
  } else {
    console.log(`${file}: the V8 expectations are not recomputed, since this Node has Unicode ${process.versions.unicode} and std has ${PINNED_UNICODE}`);
  }
  let next = 0;
  const cases = build((name, args) => {
    const item = references[next++];
    assert.deepEqual(item?.slice(0, 2), [name, args], `${file} is not for these cases at case ${next - 1}; run ${command} with a Node with Unicode ${PINNED_UNICODE}`);
    return item;
  });
  assert.equal(next, references.length, `${file} has more cases than the suite; run ${command} with a Node with Unicode ${PINNED_UNICODE}`);
  return cases;
}

function literal(value) {
  if (typeof value === "bigint") return `${value}n`;
  if (typeof value === "string") return JSON.stringify(value);
  if (Array.isArray(value)) return `[${value.map(literal).join(", ")}]`;
  assert.ok(Number.isSafeInteger(value) && !Object.is(value, -0), `${value}: not a value of a case`);
  return String(value);
}

/// The text of a reference file: a header, then `export const cases`, one `[export, arguments, expected]` per line
/// with BigInt values as literals, so that the imported cases equal the computed ones under `assert.deepEqual`.
export function referencesSource(command, suite, cases) {
  const text = `// Generated by \`${command}\` with Node ${process.version} (process.versions.unicode ${process.versions.unicode}, ICU ${process.versions.icu}).\n`
    + `// The V8 expectations of the \`${suite}\` suite of tests/features.mjs with std's Unicode ${PINNED_UNICODE} (tests/pinned-unicode.mjs). Do not edit.\n`
    + `export const cases = [\n${cases.map((item) => `  ${literal(item)},\n`).join("")}];\n`;
  const bytes = Buffer.byteLength(text);
  assert.ok(bytes < 1 << 20, `${bytes} bytes: a reference file stays under 1 MiB`);
  return text;
}
