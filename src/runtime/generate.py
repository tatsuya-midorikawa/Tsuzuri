"""Regenerate target-neutral numeric IR using Clang; no build-time C dependency."""
import os
from pathlib import Path
import re
import subprocess

directory = Path(__file__).resolve().parent


def floor_log2_ten(exponent):
    if exponent >= 0:
        return (10**exponent).bit_length() - 1
    return -(10**-exponent).bit_length()


def write_tables():
    schubfach = []
    for k in range(-324, 293):
        scale = floor_log2_ten(-k) - 125
        numerator, denominator = (10**-k, 1) if k <= 0 else (1, 10**k)
        if scale < 0:
            numerator <<= -scale
        else:
            denominator <<= scale
        g = numerator // denominator + 1
        assert (1 << 125) < g < (1 << 126)
        schubfach.extend((g >> 63, g & ((1 << 63) - 1)))
    powers = []
    for q in range(-342, 309):
        if q >= 0:
            p = 5**q
            shift = p.bit_length() - 128
            c = p >> shift if shift >= 0 else p << -shift
        else:
            p = 5**-q
            z = p.bit_length()
            if q >= -27:
                c = (1 << (z + 127)) // p + 1
            else:
                c = (1 << (2 * z + 128)) // p + 1
                c >>= max(0, c.bit_length() - 128)
        assert (1 << 127) <= c < (1 << 128)
        powers.extend((c >> 64, c & ((1 << 64) - 1)))
    assert len(schubfach) == 1234 and len(powers) == 1302
    assert 8 * (len(schubfach) + len(powers)) <= 24576
    text = "/* Generated by generate.py. Do not edit. */\n"
    for name, words in (("tzrt_schubfach_g", schubfach), ("tzrt_pow5", powers)):
        text += f"static const u64 {name}[{len(words)}] = {{\n"
        text += "".join(f"    0x{word:016x}ULL,\n" for word in words)
        text += "};\n"
    (directory / "numeric_tables.h").write_text(text)


write_tables()
result = subprocess.run(
    [os.environ.get("TSUZURI_CLANG", "clang"), "--target=x86_64-unknown-linux-gnu",
     "-std=c11", "-O1", "-ffreestanding", "-fno-builtin", "-fno-stack-protector",
     "-S", "-emit-llvm", str(directory / "numeric.c"), "-o", "-"],
    check=True, capture_output=True, text=True,
)
text = result.stdout
text = re.sub(r"^(source_filename|target |!llvm\.|; ModuleID).*?\n", "", text, flags=re.M)
text = re.sub(r' "target-[^"]+"="[^"]*"', "", text)
text = re.sub(r" captures\([^)]*\)", "", text)
text = re.sub(r" range\([^)]*\)", "", text)
text = re.sub(r" initializes\(\([^)]*\)\)", "", text)
text = text.replace(" dead_on_unwind", "").replace(" writable", "")
text = text.replace("getelementptr inbounds nuw", "getelementptr inbounds")
text = text.replace("getelementptr nuw", "getelementptr")
text = text.replace("or disjoint", "or").replace("zext nneg", "zext")
text = re.sub(r"trunc (?:nuw |nsw )+", "trunc ", text)
text = text.replace("define hidden ", "define weak hidden ")
text = re.sub(r"!llvm\.loop !\d+", "", text)
text = re.sub(r",\s*\n", "\n", text)
text = "; Generated from numeric.c by generate.py. Do not edit.\n" + text
(directory / "numeric.ll").write_text(text)
