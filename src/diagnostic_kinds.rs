impl DiagnosticKind {
    /// `Warning` for a `W` code, `Error` for every other code.
    pub fn severity(self) -> Severity {
        if self.code().starts_with('W') {
            Severity::Warning
        } else {
            Severity::Error
        }
    }

    /// The kinds of `code`, by id.
    pub fn kinds_with_code(code: &str) -> Vec<DiagnosticKind> {
        let mut kinds: Vec<_> = Self::ALL
            .iter()
            .copied()
            .filter(|kind| kind.code() == code)
            .collect();
        kinds.sort_by_key(|kind| kind.id());
        kinds
    }

    /// Every code that a kind belongs to, sorted and without duplicates.
    pub fn codes() -> Vec<&'static str> {
        let mut codes: Vec<_> = Self::ALL.iter().map(|kind| kind.code()).collect();
        codes.sort_unstable();
        codes.dedup();
        codes
    }
}
