//! `tsuzuri bindgen` (E11): Tsuzuri declarations generated from a C header.
//!
//! The driver runs Clang and passes its JSON AST and its `-E -dD` output to
//! [`generate_with`]. Everything in this module is a pure function of its input, so
//! the same Clang, header, include directories, and annotations always give the same
//! bytes. A declaration is generated only when its C ABI provably matches the Tsuzuri
//! host ABI: Clang's type spelling, with typedefs expanded, must match a fixed table
//! exactly, and only LP64 targets are accepted. Pointer-and-length buffers and
//! ownership-taking handle parameters need an explicit annotation (`--buffer`,
//! `--consume`), because a C declaration does not say either. Every other declaration
//! of the header becomes a `// skipped` line and a `W2002` warning instead of a guess.

use std::collections::{BTreeMap, BTreeSet};
use std::ffi::{OsStr, OsString};
use std::ops::Range;
use std::path::PathBuf;

use serde_json::Value;

/// The first line of every generated file; bindgen overwrites only files that start with it.
pub const MARKER: &str = "// Generated by tsuzuri bindgen. Do not edit.";
/// The most bytes bindgen reads from one Clang invocation.
pub const MAX_AST_BYTES: usize = 256 * 1024 * 1024;
const MAX_TYPEDEF_DEPTH: usize = 32;
const MAX_TYPE_NESTING: usize = 32;
const OPTIONS: &str = "bindgen accepts only -o, --include-dir, --buffer, --consume, and --json";
const BUFFER_USAGE: &str = "--buffer takes FUNCTION:POINTER:LENGTH with C names or 1-based parameter positions, such as --buffer sum:values:count";
const CONSUME_USAGE: &str = "--consume takes FUNCTION:PARAMETER with a C name or a 1-based parameter position, such as --consume close:handle";

/// `tsuzuri bindgen HEADER -o OUTPUT.tz [--include-dir DIR]... [--buffer F:P:L]...
/// [--consume F:P]... [--json]`.
#[derive(Clone, Debug, Default, PartialEq, Eq)]
pub struct Arguments {
    pub header: PathBuf,
    pub output: PathBuf,
    /// Passed to Clang as `-I DIR` in this order; they only resolve includes.
    pub include_dirs: Vec<PathBuf>,
    pub buffers: Vec<BufferAnnotation>,
    pub consumes: Vec<ConsumeAnnotation>,
    pub json: bool,
}

/// A parameter that an annotation names: its C name or its position, counted from 1.
#[derive(Clone, Debug, PartialEq, Eq)]
pub enum ParameterName {
    Name(String),
    Position(usize),
}

impl std::fmt::Display for ParameterName {
    fn fmt(&self, formatter: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            Self::Name(name) => formatter.write_str(name),
            Self::Position(position) => write!(formatter, "{position}"),
        }
    }
}

/// `--buffer FUNCTION:POINTER:LENGTH`: the pointer and the element count that follows
/// it are one Tsuzuri buffer parameter, `ref [T]`.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct BufferAnnotation {
    pub function: String,
    pub pointer: ParameterName,
    pub length: ParameterName,
}

/// `--consume FUNCTION:PARAMETER`: the function takes ownership of the opaque handle
/// passed in that parameter, so it is a move of the handle instead of a borrow.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct ConsumeAnnotation {
    pub function: String,
    pub parameter: ParameterName,
}

fn parameter_name(text: &str) -> Option<ParameterName> {
    if !text.is_empty() && text.bytes().all(|byte| byte.is_ascii_digit()) {
        return text
            .parse()
            .ok()
            .filter(|position| *position >= 1)
            .map(ParameterName::Position);
    }
    ascii_identifier(text).then(|| ParameterName::Name(text.to_owned()))
}

/// Splits `FUNCTION:PARAMETER...` into a C function name and parameter names.
fn annotation(
    value: Option<&OsString>,
    count: usize,
    usage: &str,
) -> Result<(String, Vec<ParameterName>), String> {
    let parts: Vec<&str> = value
        .and_then(|value| value.to_str())
        .map(|value| value.split(':').collect())
        .unwrap_or_default();
    if parts.len() != count + 1 || !ascii_identifier(parts[0]) {
        return Err(usage.into());
    }
    let parameters = parts[1..]
        .iter()
        .map(|part| parameter_name(part))
        .collect::<Option<Vec<_>>>()
        .ok_or(usage)?;
    Ok((parts[0].to_owned(), parameters))
}

/// Parses the arguments after `bindgen`. The error is an `E2000` message.
pub fn parse_arguments(arguments: &[OsString]) -> Result<Arguments, String> {
    let mut headers = Vec::new();
    let mut output = None;
    let mut include_dirs = Vec::new();
    let mut buffers: Vec<BufferAnnotation> = Vec::new();
    let mut consumes: Vec<ConsumeAnnotation> = Vec::new();
    let mut json = false;
    let mut paths_only = false;
    let mut rest = arguments.iter();
    while let Some(argument) = rest.next() {
        if !paths_only {
            match argument.to_str() {
                Some("--") => {
                    paths_only = true;
                    continue;
                }
                Some("--json") => {
                    json = true;
                    continue;
                }
                Some("-o" | "--output") => {
                    if output.is_some() {
                        return Err("output specified more than once".into());
                    }
                    output = Some(PathBuf::from(rest.next().ok_or("--output needs a value")?));
                    continue;
                }
                Some("--include-dir") => {
                    include_dirs.push(PathBuf::from(
                        rest.next().ok_or("--include-dir needs a value")?,
                    ));
                    continue;
                }
                Some("--buffer") => {
                    let (function, mut parameters) = annotation(rest.next(), 2, BUFFER_USAGE)?;
                    let length = parameters.pop().expect("two parameters");
                    let pointer = parameters.pop().expect("two parameters");
                    if buffers
                        .iter()
                        .any(|buffer| buffer.function == function && buffer.pointer == pointer)
                    {
                        return Err(format!(
                            "--buffer {function}:{pointer} is specified more than once"
                        ));
                    }
                    buffers.push(BufferAnnotation {
                        function,
                        pointer,
                        length,
                    });
                    continue;
                }
                Some("--consume") => {
                    let (function, mut parameters) = annotation(rest.next(), 1, CONSUME_USAGE)?;
                    let parameter = parameters.pop().expect("one parameter");
                    if consumes.iter().any(|consume| {
                        consume.function == function && consume.parameter == parameter
                    }) {
                        return Err(format!(
                            "--consume {function}:{parameter} is specified more than once"
                        ));
                    }
                    consumes.push(ConsumeAnnotation {
                        function,
                        parameter,
                    });
                    continue;
                }
                Some(value) if value.starts_with('-') => return Err(OPTIONS.into()),
                _ => {}
            }
        }
        headers.push(PathBuf::from(argument));
    }
    let [header] = <[PathBuf; 1]>::try_from(headers)
        .map_err(|_| "bindgen requires exactly one header path".to_owned())?;
    let output = output.ok_or("bindgen requires -o OUTPUT.tz")?;
    if output.extension() != Some(OsStr::new("tz")) {
        return Err("bindgen output must have the .tz extension".into());
    }
    let module = output.file_stem().and_then(OsStr::to_str).unwrap_or("");
    if !module.starts_with(|first: char| first.is_ascii_uppercase())
        || !module
            .bytes()
            .all(|byte| byte.is_ascii_alphanumeric() || byte == b'_')
    {
        return Err(format!(
            "bindgen output '{}' is not a module file name; start it with an uppercase ASCII letter followed by letters, digits, or '_', as in Zlib.tz",
            output.display()
        ));
    }
    Ok(Arguments {
        header,
        output,
        include_dirs,
        buffers,
        consumes,
        json,
    })
}

/// What the generated header comment records about the input.
pub struct HeaderInfo<'a> {
    /// The absolute path passed to Clang; a declaration belongs to the header when
    /// Clang's AST places it in this file.
    pub path: &'a str,
    pub file_name: &'a str,
    /// SHA-256 of the header's bytes in lowercase hex.
    pub sha256: &'a str,
    /// The first line of `clang --version`.
    pub clang_version: &'a str,
    /// The output of `clang -dumpmachine`.
    pub target: &'a str,
}

/// A header declaration that bindgen did not convert, reported as `W2002`.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Skipped {
    /// The C name.
    pub name: String,
    pub reason: String,
    /// The byte range of the declaration's name in the header.
    pub offset: usize,
    pub length: usize,
}

#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Generated {
    pub text: String,
    pub skipped: Vec<Skipped>,
}

/// Whether bindgen accepts Clang's target triple: 64-bit x86 and ARM with 64-bit
/// `long` and pointers (LP64), which excludes Windows (LLP64) and the ILP32 ABIs.
pub fn lp64_target(triple: &str) -> bool {
    let architecture = triple.split('-').next().unwrap_or("");
    matches!(architecture, "x86_64" | "aarch64" | "arm64")
        && !["windows", "mingw", "cygwin", "uefi", "gnux32", "ilp32"]
            .iter()
            .any(|system| triple.contains(system))
}

/// Converts the JSON AST of `clang -Xclang -ast-dump=json` for the header into a
/// Tsuzuri module, without macros or annotations. `Err` means the AST does not have
/// the shape Clang writes.
pub fn generate(ast: &Value, header: &HeaderInfo) -> Result<Generated, String> {
    generate_with(ast, header, &Extras::default()).map_err(|failure| match failure {
        Failure::Ast(message) | Failure::Annotation(message) => message,
    })
}

/// What bindgen reads besides the AST.
#[derive(Clone, Copy, Debug, Default)]
pub struct Extras<'a> {
    /// The output of `clang -E -dD` for the header: the header's object-like macros
    /// whose replacement is one integer literal become constants.
    pub preprocessed: Option<&'a str>,
    /// The header's bytes, which place each macro at its line.
    pub header_text: &'a [u8],
    pub buffers: &'a [BufferAnnotation],
    pub consumes: &'a [ConsumeAnnotation],
}

#[derive(Clone, Debug, PartialEq, Eq)]
pub enum Failure {
    /// The AST does not have the shape Clang writes (`E2002`).
    Ast(String),
    /// An annotation names a function or a parameter that the header does not
    /// declare, or names one parameter twice (`E2000`).
    Annotation(String),
}

/// [`generate`] with macros and the `--buffer` and `--consume` annotations.
pub fn generate_with(
    ast: &Value,
    header: &HeaderInfo,
    extras: &Extras,
) -> Result<Generated, Failure> {
    let nodes = ast
        .get("inner")
        .and_then(Value::as_array)
        .ok_or_else(|| Failure::Ast("the translation unit has no 'inner' array".into()))?;
    let declarations = header_declarations(nodes, header.path).map_err(Failure::Ast)?;
    let tables = Tables::new(nodes);
    let macros = extras
        .preprocessed
        .map(|text| header_macros(text, header.path, extras.header_text))
        .unwrap_or_default();
    let mut emitter = Emitter::new(&tables, header.target, extras);
    emitter.collect_types(&declarations);
    // Declarations and macros in header order: a later name that collides is skipped.
    let mut macros = macros.into_iter().peekable();
    for (index, declaration) in declarations.iter().enumerate() {
        if !declaration.owned {
            continue;
        }
        while let Some(definition) = macros.next_if(|macro_| macro_.offset < declaration.offset) {
            emitter.definition(&definition);
        }
        emitter.declaration(index, declaration)?;
    }
    for definition in macros {
        emitter.definition(&definition);
    }
    emitter.check_annotations()?;
    Ok(emitter.finish(header))
}

