fn ascii_identifier(name: &str) -> bool {
    let mut bytes = name.bytes();
    bytes
        .next()
        .is_some_and(|first| first == b'_' || first.is_ascii_alphabetic())
        && bytes.all(|byte| byte == b'_' || byte.is_ascii_alphanumeric())
}

/// `glClearColor` → `gl_clear_color`: an underscore before each uppercase letter that
/// follows a lowercase letter or a digit, then ASCII lowercase.
fn snake_case(name: &str) -> String {
    let mut result = String::with_capacity(name.len() + 4);
    let mut previous: Option<char> = None;
    for character in name.chars() {
        if character.is_ascii_uppercase()
            && previous
                .is_some_and(|previous| previous.is_ascii_lowercase() || previous.is_ascii_digit())
        {
            result.push('_');
        }
        result.push(character.to_ascii_lowercase());
        previous = Some(character);
    }
    result
}

/// `point_t` → `PointT`, `SDL_Rect` → `SDLRect`; a `C` prefix when the result would
/// not start with an uppercase letter.
fn pascal_case(name: &str) -> String {
    let mut result: String = name
        .split('_')
        .filter(|part| !part.is_empty())
        .map(|part| {
            let mut characters = part.chars();
            let first = characters.next().map(|first| first.to_ascii_uppercase());
            first.into_iter().chain(characters).collect::<String>()
        })
        .collect();
    if !result.starts_with(|first: char| first.is_ascii_uppercase()) {
        result.insert(0, 'C');
    }
    result
}

/// Whether the lexer reads `name` as a plain identifier rather than a keyword.
fn plain_identifier(name: &str) -> bool {
    crate::lexer::lex(name).is_ok_and(|tokens| {
        matches!(
            tokens.as_slice(),
            [first, ..] if first.kind == crate::syntax::TokenKind::Ident(name.to_owned())
        ) && tokens.len() == 2
    })
}

/// A function or constant name the checker accepts: keywords, `_`, and the
/// unqualified builtins (`sqrt`, `abs`, ...) get a trailing `_`.
fn value_name(name: String) -> String {
    if !plain_identifier(&name)
        || name == "_"
        || crate::check::Builtin::ALL
            .iter()
            .any(|builtin| builtin.name() == name)
    {
        name + "_"
    } else {
        name
    }
}

/// A record, alias, or extern type name the checker accepts.
fn type_name(name: String) -> String {
    if !plain_identifier(&name) || crate::check::reserved_type_name(&name) {
        name + "_"
    } else {
        name
    }
}

fn field_name(name: &str) -> String {
    value_name(snake_case(name))
}

/// Comment text with every character outside 0x20–0x7E replaced by `?`, so a file name,
/// a type, or a version cannot start a new line of generated code.
fn sanitize(text: &str) -> String {
    text.chars()
        .map(|character| {
            if (' '..='~').contains(&character) {
                character
            } else {
                '?'
            }
        })
        .collect()
}

