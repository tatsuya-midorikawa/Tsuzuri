// Which declarations belong to the header

/// A top-level declaration and where its name is.
struct Declaration<'a> {
    node: &'a Value,
    kind: &'a str,
    owned: bool,
    offset: usize,
    length: usize,
}

/// Clang writes a location's `file` only when it differs from the previously written
/// location, so the file of each declaration is known only by visiting every location
/// in the order Clang printed them: `loc` (spelling, then expansion), `range` (begin,
/// then end), then the children. `serde_json` objects do not keep key order, so the
/// order is fixed here rather than taken from the map.
fn header_declarations<'a>(nodes: &'a [Value], path: &str) -> Result<Vec<Declaration<'a>>, String> {
    let mut tracker = Tracker::default();
    let mut declarations = Vec::with_capacity(nodes.len());
    for node in nodes {
        let kind = node
            .get("kind")
            .and_then(Value::as_str)
            .ok_or("a declaration of the translation unit has no 'kind'")?;
        tracker.location(node.get("loc"));
        // A declaration expanded from a macro belongs to the file of the expansion.
        let file = tracker.current;
        tracker.range(node.get("range"));
        tracker.children(node);
        let (offset, length) = position(node);
        declarations.push(Declaration {
            node,
            kind,
            owned: file == Some(path) && !flag(node, "isImplicit"),
            offset,
            length,
        });
    }
    Ok(declarations)
}

#[derive(Default)]
struct Tracker<'a> {
    current: Option<&'a str>,
}

impl<'a> Tracker<'a> {
    fn location(&mut self, location: Option<&'a Value>) {
        let Some(location) = location else {
            return;
        };
        let spelling = location.get("spellingLoc");
        let expansion = location.get("expansionLoc");
        if spelling.is_none() && expansion.is_none() {
            self.bare(location);
        }
        for part in [spelling, expansion].into_iter().flatten() {
            self.bare(part);
        }
    }

    fn bare(&mut self, location: &'a Value) {
        // `includedFrom` also has a `file`, but Clang does not count it as written.
        if let Some(file) = location.get("file").and_then(Value::as_str) {
            self.current = Some(file);
        }
    }

    fn range(&mut self, range: Option<&'a Value>) {
        if let Some(range) = range {
            self.location(range.get("begin"));
            self.location(range.get("end"));
        }
    }

    fn children(&mut self, node: &'a Value) {
        for key in ["array_filler", "inner"] {
            for child in node
                .get(key)
                .and_then(Value::as_array)
                .into_iter()
                .flatten()
            {
                // serde_json limits nesting to 128, which bounds this recursion.
                self.location(child.get("loc"));
                self.range(child.get("range"));
                self.children(child);
            }
        }
    }
}

/// The byte range of a node's name: the expansion of a macro, else the location itself.
fn position(node: &Value) -> (usize, usize) {
    let Some(location) = node.get("loc") else {
        return (0, 0);
    };
    let location = location.get("expansionLoc").unwrap_or(location);
    let number = |key| {
        location
            .get(key)
            .and_then(Value::as_u64)
            .and_then(|value| usize::try_from(value).ok())
            .unwrap_or(0)
    };
    (number("offset"), number("tokLen"))
}

fn flag(node: &Value, key: &str) -> bool {
    node.get(key).and_then(Value::as_bool) == Some(true)
}

fn text<'a>(node: &'a Value, key: &str) -> Option<&'a str> {
    node.get(key).and_then(Value::as_str)
}

fn name(node: &Value) -> &str {
    text(node, "name").unwrap_or("")
}

fn kind(node: &Value) -> &str {
    text(node, "kind").unwrap_or("")
}

/// The spelled and desugared C type of a node.
fn node_type(node: &Value) -> (&str, Option<&str>) {
    let ty = node.get("type");
    let spelled = ty.and_then(|ty| text(ty, "qualType")).unwrap_or("");
    let desugared = ty.and_then(|ty| text(ty, "desugaredQualType"));
    (spelled, desugared)
}

fn children(node: &Value) -> impl Iterator<Item = &Value> {
    node.get("inner")
        .and_then(Value::as_array)
        .into_iter()
        .flatten()
}

fn has_attribute(node: &Value, kinds: &[&str]) -> bool {
    children(node).any(|child| kinds.contains(&kind(child)))
}

