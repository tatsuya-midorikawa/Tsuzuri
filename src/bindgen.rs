/// An object-like `#define` of the header, as it stands after the whole header.
#[derive(Debug, PartialEq, Eq)]
struct Definition<'p> {
    name: &'p str,
    body: &'p str,
    /// The byte range of the macro's name in the header.
    offset: usize,
    length: usize,
}

/// The header's own object-like macros from `clang -E -dD`, in header order. Line
/// markers (`# 12 "/path/x.h" 2`) name the file and line of the next output line, and
/// each following line is the next source line, so every `#define` is placed at its
/// line. A later `#undef` or redefinition (in any file) decides the final state.
fn header_macros<'p>(preprocessed: &'p str, path: &str, header_text: &[u8]) -> Vec<Definition<'p>> {
    let mut in_header = false;
    let mut line = 1usize;
    let mut last: BTreeMap<&'p str, Option<(&'p str, usize)>> = BTreeMap::new();
    for text in preprocessed.split('\n') {
        let text = text.strip_suffix('\r').unwrap_or(text);
        if let Some((number, file)) = linemarker(text) {
            in_header = file == path.as_bytes();
            line = number;
            continue;
        }
        if let Some(rest) = text.strip_prefix("#define ") {
            let end = rest
                .find(|character: char| character == '(' || character.is_ascii_whitespace())
                .unwrap_or(rest.len());
            let (name, after) = rest.split_at(end);
            // A function-like macro has `(` right after its name.
            let object_like = !after.starts_with('(');
            last.insert(
                name,
                (in_header && object_like).then(|| (after.trim(), line)),
            );
        } else if let Some(rest) = text.strip_prefix("#undef ") {
            last.insert(rest.trim(), None);
        }
        line += 1;
    }
    let starts = line_starts(header_text);
    let mut definitions: Vec<_> = last
        .into_iter()
        .filter_map(|(name, definition)| {
            let (body, line) = definition?;
            let (offset, length) = macro_position(header_text, &starts, line, name);
            Some(Definition {
                name,
                body,
                offset,
                length,
            })
        })
        .collect();
    definitions.sort_by_key(|definition| (definition.offset, definition.name));
    definitions
}

/// `# LINE "FILE" FLAGS...`, with the file name's C escapes undone.
fn linemarker(text: &str) -> Option<(usize, Vec<u8>)> {
    let rest = text.strip_prefix("# ")?;
    let digits = rest.find(|character: char| !character.is_ascii_digit())?;
    let line = rest[..digits].parse().ok()?;
    let quoted = rest[digits..].strip_prefix(" \"")?.as_bytes();
    let mut file = Vec::new();
    let mut index = 0;
    loop {
        match *quoted.get(index)? {
            b'"' => return Some((line, file)),
            b'\\' => {
                index += 1;
                match *quoted.get(index)? {
                    b'n' => file.push(b'\n'),
                    b't' => file.push(b'\t'),
                    digit @ b'0'..=b'7' => {
                        let mut value = u32::from(digit - b'0');
                        while index + 1 < quoted.len()
                            && value < 0o40
                            && (b'0'..=b'7').contains(&quoted[index + 1])
                        {
                            index += 1;
                            value = value * 8 + u32::from(quoted[index] - b'0');
                        }
                        file.push(u8::try_from(value).ok()?);
                    }
                    other => file.push(other),
                }
            }
            other => file.push(other),
        }
        index += 1;
    }
}

/// The byte offset of each line; `\r\n`, `\n`, and `\r` end a line, as in Clang.
fn line_starts(text: &[u8]) -> Vec<usize> {
    let mut starts = vec![0];
    let mut index = 0;
    while index < text.len() {
        match text[index] {
            b'\r' if text.get(index + 1) == Some(&b'\n') => {
                index += 2;
                starts.push(index);
            }
            b'\r' | b'\n' => {
                index += 1;
                starts.push(index);
            }
            _ => index += 1,
        }
    }
    starts
}

/// Where the name of the `#define` on `line` is; the start of the line when the
/// directive is spelled in a way this does not follow.
fn macro_position(text: &[u8], starts: &[usize], line: usize, name: &str) -> (usize, usize) {
    let Some(&start) = line.checked_sub(1).and_then(|index| starts.get(index)) else {
        return (0, 0);
    };
    let end = starts.get(line).copied().unwrap_or(text.len());
    let source = &text[start..end];
    if let Some(at) = source.windows(6).position(|window| window == b"define") {
        let mut index = at + 6;
        while matches!(source.get(index), Some(b' ' | b'\t')) {
            index += 1;
        }
        if source[index..].starts_with(name.as_bytes()) {
            return (start + index, name.len());
        }
    }
    (start, 0)
}

#[derive(Debug, PartialEq, Eq)]
enum MacroValue {
    /// Not one integer literal: ignored.
    NotInteger,
    Integer(i128, Scalar),
    /// An integer literal that bindgen cannot represent exactly: skipped with `W2002`.
    Invalid(String),
}

/// The value of a macro whose replacement is one integer literal with optional
/// parentheses and unary minus, typed by C's rules for integer constants on LP64.
fn macro_value(body: &str) -> MacroValue {
    let Some(tokens) = macro_tokens(body) else {
        return MacroValue::NotInteger;
    };
    let mut rest = tokens.as_slice();
    let mut negations = 0usize;
    let literal = loop {
        match rest {
            [literal]
                if literal.starts_with(|first: char| first.is_ascii_digit() || first == '.') =>
            {
                break *literal;
            }
            ["-", inner @ ..] => {
                negations += 1;
                rest = inner;
            }
            ["(", .., ")"] if closing(rest) == Some(rest.len() - 1) => {
                rest = &rest[1..rest.len() - 1]
            }
            _ => return MacroValue::NotInteger,
        }
    };
    match integer_literal(literal) {
        Ok(None) => MacroValue::NotInteger,
        Err(reason) => MacroValue::Invalid(reason),
        Ok(Some((value, scalar))) => {
            let mut value = i128::from(value);
            // Negating twice is the identity in both signed and unsigned arithmetic, and a
            // literal never exceeds its signed type's maximum, so one negation cannot overflow.
            if negations % 2 == 1 {
                value = match scalar {
                    Scalar::I32u => (-value).rem_euclid(1 << 32),
                    Scalar::I64u => (-value).rem_euclid(1 << 64),
                    _ => -value,
                };
            }
            MacroValue::Integer(value, scalar)
        }
    }
}

/// The tokens of a replacement list made only of parentheses, `-`, and preprocessing
/// numbers; `None` for anything else.
fn macro_tokens(body: &str) -> Option<Vec<&str>> {
    let bytes = body.as_bytes();
    let mut tokens = Vec::new();
    let mut index = 0;
    while index < bytes.len() {
        let byte = bytes[index];
        if byte.is_ascii_whitespace() {
            index += 1;
        } else if byte == b'(' || byte == b')' {
            tokens.push(&body[index..index + 1]);
            index += 1;
        } else if byte == b'-' {
            // `--` is the decrement operator, not two minus signs.
            if bytes.get(index + 1) == Some(&b'-') {
                return None;
            }
            tokens.push("-");
            index += 1;
        } else if byte.is_ascii_digit()
            || (byte == b'.' && bytes.get(index + 1).is_some_and(u8::is_ascii_digit))
        {
            let start = index;
            index += 1;
            while index < bytes.len() {
                let next = bytes[index];
                let exponent_sign = matches!(next, b'+' | b'-')
                    && matches!(bytes[index - 1], b'e' | b'E' | b'p' | b'P');
                if !(next.is_ascii_alphanumeric() || next == b'_' || next == b'.' || exponent_sign)
                {
                    break;
                }
                index += 1;
            }
            tokens.push(&body[start..index]);
        } else {
            return None;
        }
        if tokens.len() > 64 {
            return None;
        }
    }
    Some(tokens)
}

/// The index of the `)` that closes the `(` at the start of `tokens`.
fn closing(tokens: &[&str]) -> Option<usize> {
    let mut depth = 0usize;
    for (index, token) in tokens.iter().enumerate() {
        match *token {
            "(" => depth += 1,
            ")" => {
                depth -= 1;
                if depth == 0 {
                    return Some(index);
                }
            }
            _ => {}
        }
    }
    None
}

/// A C integer constant (C17 6.4.4.1 with GNU binary literals) and its type on LP64:
/// `int` → `i32`, `unsigned int` → `i32u`, `long` and `long long` → `i64`,
/// `unsigned long` and `unsigned long long` → `i64u`. `Ok(None)` for a floating constant.
fn integer_literal(text: &str) -> Result<Option<(u64, Scalar)>, String> {
    let lower = text.to_ascii_lowercase();
    let bytes = text.as_bytes();
    let (radix, prefix) = if lower.starts_with("0x") {
        (16, 2)
    } else if lower.starts_with("0b") {
        (2, 2)
    } else if bytes.len() > 1 && bytes[0] == b'0' && bytes[1].is_ascii_digit() {
        (8, 1)
    } else {
        (10, 0)
    };
    let floating = text.contains('.')
        || if radix == 16 {
            lower.contains('p')
        } else {
            lower.contains('e')
        };
    if floating {
        return Ok(None);
    }
    let invalid = || format!("'{text}' is not a valid C integer literal");
    let body = &text[prefix..];
    let digits = body
        .find(|character: char| {
            !if radix == 16 {
                character.is_ascii_hexdigit()
            } else {
                character.is_ascii_digit()
            }
        })
        .unwrap_or(body.len());
    let (digits, suffix) = body.split_at(digits);
    if digits.is_empty() {
        return Err(invalid());
    }
    let mut value = 0u128;
    for character in digits.chars() {
        value =
            value * u128::from(radix) + u128::from(character.to_digit(radix).ok_or_else(invalid)?);
        if value > u128::from(u64::MAX) {
            return Err(format!("integer literal '{text}' does not fit in 64 bits"));
        }
    }
    let (unsigned, longs) = match suffix.to_ascii_lowercase().as_str() {
        "" => (false, 0),
        "u" => (true, 0),
        "l" => (false, 1),
        "ul" | "lu" => (true, 1),
        "ll" => (false, 2),
        "ull" | "llu" => (true, 2),
        _ => {
            return Err(format!(
                "integer literal '{text}' has a suffix that bindgen does not convert"
            ));
        }
    };
    if longs == 2 && !(suffix.contains("ll") || suffix.contains("LL")) {
        return Err(invalid());
    }
    let decimal = radix == 10;
    let candidates: &[Scalar] = match (unsigned, longs, decimal) {
        (false, 0, true) => &[Scalar::I32, Scalar::I64],
        (false, 0, false) => &[Scalar::I32, Scalar::I32u, Scalar::I64, Scalar::I64u],
        (true, 0, _) => &[Scalar::I32u, Scalar::I64u],
        (false, 1, true) | (false, 2, true) => &[Scalar::I64],
        (false, _, false) => &[Scalar::I64, Scalar::I64u],
        (true, _, _) => &[Scalar::I64u],
        (false, _, true) => &[Scalar::I64],
    };
    let maximum = |scalar: Scalar| match scalar {
        Scalar::I32 => u128::from(i32::MAX.unsigned_abs()),
        Scalar::I32u => u128::from(u32::MAX),
        Scalar::I64 => u128::from(i64::MAX.unsigned_abs()),
        _ => u128::from(u64::MAX),
    };
    candidates
        .iter()
        .find(|scalar| value <= maximum(**scalar))
        .map(|scalar| Some((value as u64, *scalar)))
        .ok_or_else(|| {
            format!(
                "integer literal '{text}' does not fit in a signed 64-bit type; C gives it no type without a 'u' suffix"
            )
        })
}

