// C types as Clang spells them

#[derive(Clone, Copy, Debug, Default, PartialEq, Eq)]
struct Qualifiers {
    constant: bool,
    volatile: bool,
}

impl Qualifiers {
    fn union(self, other: Self) -> Self {
        Self {
            constant: self.constant || other.constant,
            volatile: self.volatile || other.volatile,
        }
    }
}

#[derive(Clone, Debug, PartialEq, Eq)]
enum CType {
    /// Specifiers without qualifiers: a builtin such as `unsigned long`, a tag such
    /// as `struct point`, or a typedef name.
    Named(String),
    /// A pointer and the qualifiers of what it points to.
    Pointer(Box<CType>, Qualifiers),
    /// A prototyped, non-variadic function type: its result and parameters.
    Function(Box<CType>, Vec<CType>),
    /// Anything else, including spellings this parser does not understand.
    Unsupported,
}

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
enum Token<'a> {
    Word(&'a str),
    Symbol(char),
}

fn tokenize(text: &str) -> Vec<(usize, Token<'_>)> {
    let bytes = text.as_bytes();
    let word = |byte: u8| byte.is_ascii_alphanumeric() || byte == b'_' || byte == b'$';
    let mut tokens = Vec::new();
    let mut index = 0;
    while index < bytes.len() {
        if bytes[index].is_ascii_whitespace() {
            index += 1;
        } else if word(bytes[index]) {
            let start = index;
            while index < bytes.len() && word(bytes[index]) {
                index += 1;
            }
            tokens.push((start, Token::Word(&text[start..index])));
        } else if text[index..].starts_with("...") {
            tokens.push((index, Token::Word("...")));
            index += 3;
        } else {
            let character = text[index..].chars().next().unwrap_or('?');
            tokens.push((index, Token::Symbol(character)));
            index += character.len_utf8();
        }
    }
    tokens
}

/// The index of the `)` that closes the `(` at `open`.
fn matching(tokens: &[(usize, Token<'_>)], open: usize) -> Option<usize> {
    let mut depth = 0usize;
    for (index, (_, token)) in tokens.iter().enumerate().skip(open) {
        match token {
            Token::Symbol('(') => depth += 1,
            Token::Symbol(')') => {
                depth -= 1;
                if depth == 0 {
                    return Some(index);
                }
            }
            _ => {}
        }
    }
    None
}

/// Parses a whole type spelling: specifiers, pointers with their qualifiers, and at
/// most one function-pointer declarator `R (*)(P, ...)`. The qualifiers returned
/// are those of the type itself (top level).
fn parse_type(text: &str) -> Option<(CType, Qualifiers)> {
    parse_tokens(&tokenize(text), 0)
}

fn parse_tokens(tokens: &[(usize, Token<'_>)], nesting: usize) -> Option<(CType, Qualifiers)> {
    if nesting > MAX_TYPE_NESTING {
        return None;
    }
    let mut parser = TypeParser {
        tokens,
        position: 0,
        nesting,
    };
    let parsed = parser.whole()?;
    (parser.position == tokens.len()).then_some(parsed)
}

struct TypeParser<'t, 'a> {
    tokens: &'t [(usize, Token<'a>)],
    position: usize,
    nesting: usize,
}

impl<'a> TypeParser<'_, 'a> {
    fn peek(&self) -> Option<Token<'a>> {
        self.tokens.get(self.position).map(|(_, token)| *token)
    }

    fn eat(&mut self, symbol: char) -> bool {
        let found = self.peek() == Some(Token::Symbol(symbol));
        self.position += usize::from(found);
        found
    }

    fn whole(&mut self) -> Option<(CType, Qualifiers)> {
        let (mut ty, mut qualifiers) = self.specifiers()?;
        while self.eat('*') {
            ty = CType::Pointer(Box::new(ty), qualifiers);
            qualifiers = self.qualifiers()?;
        }
        if self.eat('(') {
            // Only `(*)` with optional qualifiers: blocks `(^)` and nested
            // declarators are not supported.
            if !self.eat('*') {
                return None;
            }
            let pointer = self.qualifiers()?;
            if !self.eat(')') || !self.eat('(') {
                return None;
            }
            let parameters = self.parameters()?;
            let function = if parameters.prototype && !parameters.variadic {
                CType::Function(Box::new(ty), parameters.list)
            } else {
                CType::Unsupported
            };
            ty = CType::Pointer(Box::new(function), Qualifiers::default());
            qualifiers = pointer;
        }
        Some((ty, qualifiers))
    }

    fn specifiers(&mut self) -> Option<(CType, Qualifiers)> {
        let mut words = Vec::new();
        let mut qualifiers = Qualifiers::default();
        while let Some(Token::Word(word)) = self.peek() {
            self.position += 1;
            match word {
                "const" => qualifiers.constant = true,
                "volatile" => qualifiers.volatile = true,
                "restrict" | "__restrict" | "_Nonnull" | "_Nullable" | "_Null_unspecified"
                | "_Nullable_result" => {}
                "struct" | "union" | "enum" => {
                    // An anonymous tag is spelled `struct (unnamed struct at ...)`.
                    let Some(Token::Word(tag)) = self.peek() else {
                        return None;
                    };
                    self.position += 1;
                    words.push(format!("{word} {tag}"));
                }
                _ => words.push(word.to_owned()),
            }
        }
        (!words.is_empty()).then(|| (CType::Named(words.join(" ")), qualifiers))
    }

    /// The qualifiers after a `*`, which apply to the pointer itself.
    fn qualifiers(&mut self) -> Option<Qualifiers> {
        let mut qualifiers = Qualifiers::default();
        while let Some(Token::Word(word)) = self.peek() {
            match word {
                "const" => qualifiers.constant = true,
                "volatile" => qualifiers.volatile = true,
                "restrict" | "__restrict" | "_Nonnull" | "_Nullable" | "_Null_unspecified"
                | "_Nullable_result" => {}
                _ => return None,
            }
            self.position += 1;
        }
        Some(qualifiers)
    }

    /// The parameter list after its `(`, through the closing `)`.
    fn parameters(&mut self) -> Option<Parameters> {
        let mut depth = 0usize;
        let mut pieces = Vec::new();
        let mut start = self.position;
        loop {
            let (_, token) = *self.tokens.get(self.position)?;
            self.position += 1;
            match token {
                Token::Symbol('(' | '[') => depth += 1,
                Token::Symbol(')') if depth == 0 => {
                    pieces.push(start..self.position - 1);
                    break;
                }
                Token::Symbol(')' | ']') => depth = depth.checked_sub(1)?,
                Token::Symbol(',') if depth == 0 => {
                    pieces.push(start..self.position - 1);
                    start = self.position;
                }
                _ => {}
            }
        }
        Some(parameter_list(self.tokens, pieces, self.nesting))
    }
}

struct Parameters {
    list: Vec<CType>,
    /// `false` for `()`, which declares no prototype in C17.
    prototype: bool,
    variadic: bool,
}

fn parameter_list(
    tokens: &[(usize, Token<'_>)],
    mut pieces: Vec<Range<usize>>,
    nesting: usize,
) -> Parameters {
    let piece = |range: &Range<usize>| &tokens[range.clone()];
    if pieces.len() == 1 && pieces[0].is_empty() {
        return Parameters {
            list: Vec::new(),
            prototype: false,
            variadic: false,
        };
    }
    if pieces.len() == 1 && matches!(piece(&pieces[0]), [(_, Token::Word("void"))]) {
        pieces.clear();
    }
    let variadic = pieces
        .last()
        .is_some_and(|last| matches!(piece(last), [(_, Token::Word("..."))]));
    if variadic {
        pieces.pop();
    }
    Parameters {
        list: pieces
            .iter()
            .map(|range| {
                parse_tokens(piece(range), nesting + 1).map_or(CType::Unsupported, |(ty, _)| ty)
            })
            .collect(),
        prototype: true,
        variadic,
    }
}

/// A function declaration's type `R (P1, P2) attributes`, split into its parts.
struct FunctionShape {
    /// The spelling of the result type; `Err` holds the spelling of a function-pointer
    /// or block result, which is never supported.
    result: Result<String, String>,
    prototype: bool,
    /// The names in trailing `__attribute__((...))` groups; `?` marks other text.
    attributes: Vec<String>,
}

fn function_shape(text: &str) -> Option<FunctionShape> {
    let tokens = tokenize(text);
    let mut attributes = Vec::new();
    // Clang prints some calling conventions before the type (`__attribute__((x)) int
    // (int)`) and others after the parameter list.
    let mut result_start = 0;
    let mut open = 0;
    loop {
        match tokens.get(open)?.1 {
            Token::Word("__attribute__") => {
                let (name, end) = attribute_group(&tokens, open)?;
                attributes.push(name);
                if open == result_start {
                    result_start = end + 1;
                }
                open = end + 1;
            }
            // The parameter list is the first `(` that does not spell an anonymous tag.
            Token::Symbol('(')
                if open > 0
                    && matches!(tokens[open - 1].1, Token::Word("struct" | "union" | "enum")) =>
            {
                open = matching(&tokens, open)? + 1;
            }
            Token::Symbol('(') => break,
            _ => open += 1,
        }
    }
    let close = matching(&tokens, open)?;
    if matches!(
        tokens.get(open + 1).map(|token| token.1),
        Some(Token::Symbol('*' | '^'))
    ) {
        // `int (*(int))(void)` returns `int (*)(void)`: drop the function's own
        // parameter list, which directly follows the `*` and its qualifiers.
        let mut inner = open + 2;
        while matches!(tokens.get(inner).map(|token| token.1), Some(Token::Word(_))) {
            inner += 1;
        }
        let spelled = match tokens.get(inner) {
            Some((from, Token::Symbol('('))) => {
                let end = matching(&tokens, inner)?;
                format!("{}{}", &text[..*from], &text[tokens[end].0 + 1..])
            }
            _ => text.to_owned(),
        };
        return Some(FunctionShape {
            result: Err(spelled.trim().to_owned()),
            prototype: true,
            attributes,
        });
    }
    let mut index = close + 1;
    while index < tokens.len() {
        let Some((name, end)) = attribute_group(&tokens, index) else {
            attributes.push("?".to_owned());
            break;
        };
        attributes.push(name);
        index = end + 1;
    }
    let result_text = match tokens.get(result_start) {
        Some((from, _)) if result_start < open => &text[*from..tokens[open].0],
        _ => "",
    };
    Some(FunctionShape {
        result: Ok(result_text.trim().to_owned()),
        prototype: close != open + 1,
        attributes,
    })
}

/// The name in an `__attribute__((name...))` group at `start` and the index of its last `)`.
fn attribute_group(tokens: &[(usize, Token<'_>)], start: usize) -> Option<(String, usize)> {
    let group = matches!(tokens.get(start)?.1, Token::Word("__attribute__"))
        && tokens.get(start + 1)?.1 == Token::Symbol('(')
        && tokens.get(start + 2)?.1 == Token::Symbol('(');
    if !group {
        return None;
    }
    let end = matching(tokens, start + 1)?;
    let name = match tokens.get(start + 3)?.1 {
        Token::Word(name) => name.to_owned(),
        Token::Symbol(_) => "?".to_owned(),
    };
    Some((name, end))
}

/// Replaces Clang's `(unnamed struct at /abs/path:1:2)` with `(unnamed struct)`, so
/// generated text and warnings never contain absolute paths.
fn scrub(text: &str) -> String {
    let mut result = String::with_capacity(text.len());
    let mut rest = text;
    while let Some(start) = ["(unnamed ", "(anonymous "]
        .iter()
        .filter_map(|marker| rest.find(marker))
        .min()
    {
        let Some(end) = rest[start..].find(')').map(|end| start + end) else {
            break;
        };
        let inside = &rest[start..end];
        result.push_str(&rest[..start]);
        result.push_str(inside.split(" at ").next().unwrap_or(inside));
        result.push(')');
        rest = &rest[end + 1..];
    }
    result.push_str(rest);
    result
}

