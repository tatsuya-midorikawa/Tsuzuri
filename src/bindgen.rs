/// The decision for a declaration that defines a Tsuzuri type, made before any line
/// is written because functions may name a struct declared after them.
enum TypeDecision {
    Line(String),
    /// The C name, the reason, and where to report it when not at the declaration.
    Skip(String, String, Option<(usize, usize)>),
}

/// What the annotations ask of one parameter of a function.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
enum Annotated {
    Plain,
    /// `--consume`: the handle moves into the call.
    Consumed,
    /// `--buffer`: the pointer of a buffer whose length is the parameter at this index.
    Pointer(usize),
    /// `--buffer`: the length, passed with its pointer.
    Length,
}

struct Emitter<'t, 'a> {
    tables: &'t Tables<'a>,
    /// The prefix the object format adds to C symbols (`_` on Mach-O).
    symbol_prefix: &'static str,
    buffers: &'t [BufferAnnotation],
    consumes: &'t [ConsumeAnnotation],
    values: BTreeSet<String>,
    types: BTreeSet<String>,
    /// `TAG` → the generated record of `struct TAG`.
    records: BTreeMap<&'a str, String>,
    /// `TAG` → the generated `extern type` of the opaque `struct TAG`.
    handles: BTreeMap<&'a str, String>,
    decisions: BTreeMap<usize, TypeDecision>,
    /// The functions of the header, for checking that each annotation names one.
    functions: BTreeSet<&'a str>,
    lines: Vec<String>,
    skipped: Vec<Skipped>,
}

impl<'t, 'a> Emitter<'t, 'a> {
    fn new(tables: &'t Tables<'a>, target: &str, extras: &Extras<'t>) -> Self {
        Self {
            tables,
            symbol_prefix: if target.contains("apple") || target.contains("darwin") {
                "_"
            } else {
                ""
            },
            buffers: extras.buffers,
            consumes: extras.consumes,
            values: BTreeSet::new(),
            types: BTreeSet::new(),
            records: BTreeMap::new(),
            handles: BTreeMap::new(),
            decisions: BTreeMap::new(),
            functions: BTreeSet::new(),
            lines: Vec::new(),
            skipped: Vec::new(),
        }
    }

    /// Names the types of the header in header order: records, extern types, and type
    /// aliases share one namespace, and a later declaration that collides is skipped.
    fn collect_types(&mut self, declarations: &[Declaration<'a>]) {
        for (index, declaration) in declarations.iter().enumerate() {
            if !declaration.owned {
                continue;
            }
            let decision = match declaration.kind {
                "RecordDecl" if flag(declaration.node, "completeDefinition") => {
                    self.record(declaration.node)
                }
                "RecordDecl" => self.handle(declaration.node),
                "TypedefDecl" => self.alias(declaration.node),
                _ => None,
            };
            if let Some(decision) = decision {
                self.decisions.insert(index, decision);
            }
        }
    }

    /// An `extern type` for a struct that the header declares first and that no
    /// declaration of the translation unit defines. C code can hold such a struct only
    /// through pointers, which the library allocates, so a pointer to it is exactly an
    /// E12 handle: one pointer-sized value that Tsuzuri never dereferences.
    fn handle(&mut self, node: &'a Value) -> Option<TypeDecision> {
        let tag = name(node);
        if text(node, "tagUsed") != Some("struct")
            || node.get("previousDecl").is_some()
            || !self.tables.incomplete.contains(tag)
        {
            return None;
        }
        let skip = |reason: String| Some(TypeDecision::Skip(tag.to_owned(), reason, None));
        if !ascii_identifier(tag) {
            return skip("name is not an ASCII C identifier".into());
        }
        let handle = type_name(pascal_case(tag));
        if !self.types.insert(handle.clone()) {
            return skip(format!(
                "name '{handle}' collides with an earlier declaration"
            ));
        }
        self.handles.insert(tag, handle.clone());
        Some(TypeDecision::Line(format!("extern type {handle}")))
    }

    fn record(&mut self, node: &'a Value) -> Option<TypeDecision> {
        let tag = name(node);
        let skip = |name: &str, reason: &str| {
            Some(TypeDecision::Skip(name.to_owned(), reason.to_owned(), None))
        };
        if text(node, "tagUsed") == Some("union") {
            let shown = if tag.is_empty() {
                "(anonymous union)"
            } else {
                tag
            };
            return skip(shown, "C union");
        }
        if text(node, "tagUsed") != Some("struct") {
            return None;
        }
        if tag.is_empty() {
            // Reported at the typedef that names it, if any.
            let named = text(node, "id").and_then(|id| self.tables.anonymous.get(id));
            return Some(TypeDecision::Skip(
                named
                    .map_or("(anonymous struct)", |(name, _)| name)
                    .to_owned(),
                "anonymous struct; give the struct a tag".to_owned(),
                named.map(|(_, at)| *at),
            ));
        }
        if !ascii_identifier(tag) {
            return skip(tag, "name is not an ASCII C identifier");
        }
        if has_attribute(node, LAYOUT_ATTRIBUTES) {
            return skip(tag, "struct has a packing or alignment attribute");
        }
        let fields: Vec<_> = children(node)
            .filter(|child| kind(child) == "FieldDecl")
            .collect();
        if fields.is_empty() {
            return skip(tag, "struct has no fields");
        }
        let field_label = |field: &Value| match name(field) {
            "" => "(anonymous)".to_owned(),
            name => name.to_owned(),
        };
        if let Some(field) = fields.iter().find(|field| flag(field, "isBitfield")) {
            return skip(tag, &format!("bit-field '{}'", field_label(field)));
        }
        if let Some(field) = fields
            .iter()
            .find(|field| has_attribute(field, LAYOUT_ATTRIBUTES))
        {
            return skip(
                tag,
                &format!(
                    "field '{}' has an alignment or packing attribute",
                    field_label(field)
                ),
            );
        }
        let mut converted = Vec::new();
        for field in &fields {
            let (spelled, desugared) = node_type(field);
            let (ty, _) = self.tables.c_type(spelled, desugared);
            let Some(scalar) = self.tables.scalar(&ty, Role::Field) else {
                return skip(
                    tag,
                    &format!(
                        "field '{}' has unsupported type '{}'",
                        field_label(field),
                        scrub(spelled)
                    ),
                );
            };
            converted.push((name(field), scalar));
        }
        let mut names = BTreeSet::new();
        let mut rendered = Vec::new();
        for (field, scalar) in converted {
            if !ascii_identifier(field) {
                return skip(
                    tag,
                    &format!("field '{field}' is not an ASCII C identifier"),
                );
            }
            let converted = field_name(field);
            if !names.insert(converted.clone()) {
                return skip(
                    tag,
                    &format!("field '{field}' collides with an earlier field as '{converted}'"),
                );
            }
            rendered.push(format!("{converted}: {scalar}"));
        }
        let record = type_name(pascal_case(tag));
        if !self.types.insert(record.clone()) {
            return skip(
                tag,
                &format!("name '{record}' collides with an earlier declaration"),
            );
        }
        self.records.insert(tag, record.clone());
        Some(TypeDecision::Line(format!(
            "record {record} {{ {} }}",
            rendered.join(", ")
        )))
    }

    /// A type alias for a typedef that resolves to a scalar; other typedefs produce
    /// nothing, because signatures use the resolved types.
    fn alias(&mut self, node: &'a Value) -> Option<TypeDecision> {
        let typedef = name(node);
        let (ty, _) = self.tables.c_type(typedef, None);
        let CType::Named(resolved) = ty else {
            return None;
        };
        let scalar = Scalar::of(&resolved)?.name();
        if !ascii_identifier(typedef) {
            return Some(TypeDecision::Skip(
                typedef.to_owned(),
                "name is not an ASCII C identifier".to_owned(),
                None,
            ));
        }
        let alias = type_name(pascal_case(typedef));
        if !self.types.insert(alias.clone()) {
            return Some(TypeDecision::Skip(
                typedef.to_owned(),
                format!("name '{alias}' collides with an earlier declaration"),
                None,
            ));
        }
        Some(TypeDecision::Line(format!("type {alias} = {scalar}")))
    }

    fn declaration(&mut self, index: usize, declaration: &Declaration<'a>) -> Result<(), Failure> {
        let node = declaration.node;
        let at = (declaration.offset, declaration.length);
        match declaration.kind {
            "RecordDecl" | "TypedefDecl" => match self.decisions.remove(&index) {
                Some(TypeDecision::Line(line)) => self.lines.push(line),
                Some(TypeDecision::Skip(name, reason, place)) => {
                    self.skip(&name, reason, place.unwrap_or(at))
                }
                None => {}
            },
            "EnumDecl" => self.constants(node),
            "FunctionDecl" => self.function(node, at)?,
            "VarDecl" => self.skip(name(node), "global variable".into(), at),
            _ => {}
        }
        Ok(())
    }

    /// A constant for an object-like macro whose replacement is one integer literal.
    fn definition(&mut self, definition: &Definition) {
        let at = (definition.offset, definition.length);
        let (value, scalar) = match macro_value(definition.body) {
            MacroValue::NotInteger => return,
            MacroValue::Invalid(reason) => return self.skip(definition.name, reason, at),
            MacroValue::Integer(value, scalar) => (value, scalar),
        };
        if !ascii_identifier(definition.name) {
            return self.skip(
                definition.name,
                "name is not an ASCII C identifier".into(),
                at,
            );
        }
        let tsuzuri = value_name(definition.name.to_owned());
        if !self.values.insert(tsuzuri.clone()) {
            return self.skip(
                definition.name,
                format!("name '{tsuzuri}' collides with an earlier declaration"),
                at,
            );
        }
        self.lines
            .push(format!("const {tsuzuri}: {} = {value}", scalar.name()));
    }

    fn constants(&mut self, node: &'a Value) {
        for enumerator in self.tables.enumerators(node) {
            let constant = name(enumerator.node);
            let at = position(enumerator.node);
            if !ascii_identifier(constant) {
                self.skip(constant, "name is not an ASCII C identifier".into(), at);
                continue;
            }
            let Some(value) = enumerator.value else {
                self.skip(
                    constant,
                    "enumerator value is not an integer constant in the clang AST".into(),
                    at,
                );
                continue;
            };
            if i32::try_from(value).is_err() {
                self.skip(
                    constant,
                    format!("enumerator value {value} does not fit in i32"),
                    at,
                );
                continue;
            }
            let tsuzuri = value_name(constant.to_owned());
            if !self.values.insert(tsuzuri.clone()) {
                self.skip(
                    constant,
                    format!("name '{tsuzuri}' collides with an earlier declaration"),
                    at,
                );
                continue;
            }
            self.lines.push(format!("const {tsuzuri}: i32 = {value}"));
        }
    }

    fn function(&mut self, node: &'a Value, at: (usize, usize)) -> Result<(), Failure> {
        // A redeclaration produces nothing. Clang declares library builtins such as
        // `sqrt` implicitly at their first mention, so a header's own declaration of
        // one names that implicit declaration as its previous one and still counts.
        if text(node, "previousDecl")
            .is_some_and(|previous| !self.tables.builtins.contains(previous))
        {
            return Ok(());
        }
        let symbol = name(node);
        self.functions.insert(symbol);
        let parameters: Vec<&Value> = children(node)
            .filter(|child| kind(child) == "ParmVarDecl")
            .collect();
        let plan = self.annotation_plan(symbol, &parameters)?;
        match self.function_line(node, symbol, &parameters, &plan) {
            Ok(line) => self.lines.push(line),
            Err(reason) => self.skip(symbol, reason, at),
        }
        Ok(())
    }

    /// What the `--buffer` and `--consume` annotations ask of each parameter.
    fn annotation_plan(
        &self,
        symbol: &str,
        parameters: &[&Value],
    ) -> Result<Vec<Annotated>, Failure> {
        let mut plan = vec![Annotated::Plain; parameters.len()];
        let index_of = |option: &str, parameter: &ParameterName| match parameter {
            ParameterName::Position(position) if *position <= parameters.len() => Ok(position - 1),
            ParameterName::Position(position) => Err(Failure::Annotation(format!(
                "{option} names parameter {position} of '{symbol}', which has {} parameter{}",
                parameters.len(),
                if parameters.len() == 1 { "" } else { "s" }
            ))),
            ParameterName::Name(wanted) => parameters
                .iter()
                .position(|parameter| name(parameter) == wanted)
                .ok_or_else(|| {
                    Failure::Annotation(format!(
                        "{option} names parameter '{wanted}', which '{symbol}' does not have"
                    ))
                }),
        };
        let twice = |option: &str| {
            Failure::Annotation(format!(
                "{option} names a parameter of '{symbol}' that another annotation already names"
            ))
        };
        for consume in self
            .consumes
            .iter()
            .filter(|consume| consume.function == symbol)
        {
            let index = index_of("--consume", &consume.parameter)?;
            if plan[index] != Annotated::Plain {
                return Err(twice("--consume"));
            }
            plan[index] = Annotated::Consumed;
        }
        for buffer in self
            .buffers
            .iter()
            .filter(|buffer| buffer.function == symbol)
        {
            let pointer = index_of("--buffer", &buffer.pointer)?;
            let length = index_of("--buffer", &buffer.length)?;
            if pointer == length
                || plan[pointer] != Annotated::Plain
                || plan[length] != Annotated::Plain
            {
                return Err(twice("--buffer"));
            }
            plan[pointer] = Annotated::Pointer(length);
            plan[length] = Annotated::Length;
        }
        Ok(plan)
    }

    /// Every annotation must name a function of the header.
    fn check_annotations(&self) -> Result<(), Failure> {
        let names = self
            .buffers
            .iter()
            .map(|buffer| ("--buffer", buffer.function.as_str()))
            .chain(
                self.consumes
                    .iter()
                    .map(|consume| ("--consume", consume.function.as_str())),
            );
        for (option, function) in names {
            if !self.functions.contains(function) {
                return Err(Failure::Annotation(format!(
                    "{option} names '{function}', which the header does not declare as a function"
                )));
            }
        }
        Ok(())
    }

    /// The `extern` line for a function, or why it cannot have one. The checks run in
    /// the order of the `W2002` reasons in the language reference.
    fn function_line(
        &mut self,
        node: &'a Value,
        symbol: &str,
        parameters: &[&Value],
        plan: &[Annotated],
    ) -> Result<String, String> {
        if text(node, "storageClass") == Some("static") {
            return Err("function has internal linkage (static)".into());
        }
        if flag(node, "inline") {
            return Err("inline function has no guaranteed external definition".into());
        }
        if flag(node, "variadic") {
            return Err("variadic function".into());
        }
        let (spelled, _) = node_type(node);
        let shape = function_shape(spelled)
            .ok_or_else(|| format!("function type '{}' is not understood", scrub(spelled)))?;
        if !shape.prototype {
            return Err("function has no prototype".into());
        }
        if !ascii_identifier(symbol) {
            return Err("name is not an ASCII C identifier".into());
        }
        if crate::abi::RESERVED_SYMBOL_PREFIXES
            .iter()
            .any(|prefix| symbol.starts_with(prefix))
        {
            return Err("symbol uses the reserved tz_, tsuzuri, or __ prefix".into());
        }
        if crate::abi::RESERVED_HOST_SYMBOLS.contains(&symbol) {
            return Err("symbol is reserved by the Tsuzuri runtime".into());
        }
        if symbol.len() > 255 {
            return Err("symbol is longer than 255 bytes".into());
        }
        // An asm label or `overloadable` gives the function another symbol.
        let renamed =
            match text(node, "mangledName") {
                Some(mangled) => (mangled != format!("{}{symbol}", self.symbol_prefix))
                    .then(|| mangled.to_owned()),
                None => has_attribute(node, &["AsmLabelAttr", "OverloadableAttr"])
                    .then(|| "?".to_owned()),
            };
        if let Some(mangled) = renamed {
            return Err(format!(
                "symbol is renamed to '{}' by an asm label or overloading",
                sanitize(&mangled)
            ));
        }
        if let Some(attribute) = shape
            .attributes
            .iter()
            .find(|attribute| !matches!(attribute.as_str(), "noreturn" | "__noreturn__"))
        {
            return Err(format!(
                "function type has the attribute '{attribute}', which may change its calling convention"
            ));
        }
        let mut converted = Vec::new();
        for (index, parameter) in parameters.iter().enumerate() {
            let number = index + 1;
            if has_attribute(parameter, &["PassObjectSizeAttr"]) {
                return Err(format!(
                    "parameter {number} has the pass_object_size attribute, which adds a hidden argument"
                ));
            }
            let (spelled, desugared) = node_type(parameter);
            let unsupported = || {
                format!(
                    "parameter {number} has unsupported type '{}'",
                    scrub(spelled)
                )
            };
            match plan[index] {
                Annotated::Plain => converted.push(
                    self.value_type(&self.tables.c_type(spelled, desugared).0, Role::Parameter)
                        .ok_or_else(unsupported)?,
                ),
                Annotated::Consumed => converted.push(self.consumed(spelled, desugared).ok_or_else(
                    || format!("--consume names parameter {number}, which is not a pointer to an opaque struct of the header"),
                )?),
                Annotated::Pointer(length) => converted.push(self.buffer(parameters, index, length)?),
                // Passed together with its pointer.
                Annotated::Length => {}
            }
        }
        let result = match &shape.result {
            Ok(spelled) => self.value_type(&self.tables.c_type(spelled, None).0, Role::Result),
            Err(_) => None,
        }
        .ok_or_else(|| {
            let (Ok(spelled) | Err(spelled)) = &shape.result;
            format!("result has unsupported type '{}'", scrub(spelled))
        })?;
        let tsuzuri = value_name(snake_case(symbol));
        if !self.values.insert(tsuzuri.clone()) {
            return Err(format!(
                "name '{tsuzuri}' collides with an earlier declaration"
            ));
        }
        Ok(render_function(symbol, &tsuzuri, &converted, &result))
    }

    /// The Tsuzuri type of a resolved C type in a position, or `None` when the ABI
    /// does not match exactly.
    fn value_type(&self, ty: &CType, role: Role) -> Option<String> {
        if let Some(scalar) = self.tables.scalar(ty, role) {
            return Some(scalar.to_owned());
        }
        match ty {
            CType::Named(name) if name == "void" => {
                matches!(role, Role::Result | Role::CallbackResult).then(|| "unit".to_owned())
            }
            CType::Pointer(pointee, qualifiers) if !qualifiers.volatile => match pointee.as_ref() {
                CType::Named(pointee) => {
                    let tag = pointee.strip_prefix("struct ")?;
                    if let Some(handle) = self.handles.get(tag) {
                        // Parameters borrow the handle: the call neither consumes nor
                        // copies it, and what C does behind the pointer is invisible to
                        // Tsuzuri. A result is a new handle that the caller owns, except
                        // a pointer to const, which can only be borrowed.
                        return match role {
                            Role::Parameter | Role::CallbackParameter => {
                                Some(format!("ref {handle}"))
                            }
                            Role::Result if !qualifiers.constant => Some(handle.clone()),
                            _ => None,
                        };
                    }
                    // `const struct TAG *` borrows a generated record. Without `const` the
                    // host could write into the temporary copy the ABI passes.
                    (role == Role::Parameter && qualifiers.constant)
                        .then(|| self.records.get(tag).map(|record| format!("ref {record}")))
                        .flatten()
                }
                CType::Function(result, parameters) if role == Role::Parameter => {
                    self.callback(result, parameters)
                }
                _ => None,
            },
            _ => None,
        }
    }

    /// A function pointer parameter as an E12 callback: its parameters are scalars or
    /// opaque handles that C passes to Tsuzuri, and its result is a scalar or `void`.
    fn callback(&self, result: &CType, parameters: &[CType]) -> Option<String> {
        let mut signature = parameters
            .iter()
            .map(|parameter| self.value_type(parameter, Role::CallbackParameter))
            .collect::<Option<Vec<_>>>()?;
        if signature.is_empty() {
            signature.push("unit".into());
        }
        signature.push(self.value_type(result, Role::CallbackResult)?);
        Some(format!("({})", signature.join(" -> ")))
    }

    /// A parameter that `--consume` names: the handle moves into the call.
    fn consumed(&self, spelled: &str, desugared: Option<&str>) -> Option<String> {
        let (CType::Pointer(pointee, qualifiers), _) = self.tables.c_type(spelled, desugared)
        else {
            return None;
        };
        let CType::Named(pointee) = *pointee else {
            return None;
        };
        let tag = pointee.strip_prefix("struct ")?;
        (!qualifiers.volatile)
            .then(|| self.handles.get(tag).cloned())
            .flatten()
    }

    /// The pointer and the length that `--buffer` names, as one `ref [T]` parameter.
    /// The E05 buffer ABI passes exactly a pointer to the elements and an `int64_t`
    /// element count, so the C parameters must be a pointer to const elements of the
    /// same representation, followed directly by a 64-bit integer count.
    fn buffer(
        &self,
        parameters: &[&Value],
        pointer: usize,
        length: usize,
    ) -> Result<String, String> {
        let number = pointer + 1;
        if length != pointer + 1 {
            return Err(format!(
                "--buffer pairs parameter {number} with parameter {}, but the buffer ABI passes the length right after the pointer",
                length + 1
            ));
        }
        let (spelled, desugared) = node_type(parameters[pointer]);
        let (ty, _) = self.tables.c_type(spelled, desugared);
        let CType::Pointer(pointee, qualifiers) = ty else {
            return Err(format!(
                "--buffer names parameter {number}, which has type '{}', not a pointer",
                scrub(spelled)
            ));
        };
        if !qualifiers.constant || qualifiers.volatile {
            return Err(format!(
                "buffer parameter {number} has type '{}', not a pointer to const; the host could write into a shared Tsuzuri array",
                scrub(spelled)
            ));
        }
        let element = match *pointee {
            CType::Named(element) => match element.as_str() {
                "long" | "long long" => "i64",
                "double" => "f64",
                // Bytes: `void` buffers are counted in bytes.
                "unsigned char" | "char" | "void" => "ubyte",
                _ => "",
            },
            _ => "",
        };
        if element.is_empty() {
            return Err(format!(
                "buffer parameter {number} has type '{}'; Tsuzuri buffers hold 64-bit integers, doubles, or bytes",
                scrub(spelled)
            ));
        }
        let (spelled, desugared) = node_type(parameters[length]);
        let count = self.tables.c_type(spelled, desugared).0;
        let wide = matches!(&count, CType::Named(name) if matches!(name.as_str(), "long" | "long long" | "unsigned long" | "unsigned long long"));
        if !wide {
            return Err(format!(
                "buffer length parameter {} has type '{}', not a 64-bit integer",
                length + 1,
                scrub(spelled)
            ));
        }
        Ok(format!("ref [{element}]"))
    }

    fn skip(&mut self, name: &str, reason: String, (offset, length): (usize, usize)) {
        self.lines.push(format!(
            "// skipped {}: {}",
            sanitize(name),
            sanitize(&reason)
        ));
        self.skipped.push(Skipped {
            name: name.to_owned(),
            reason,
            offset,
            length,
        });
    }

    fn finish(self, header: &HeaderInfo) -> Generated {
        let mut text = format!(
            "{MARKER}\n// header: {} sha256={}\n// clang: {}\n// target: {}\n",
            sanitize(header.file_name),
            sanitize(header.sha256),
            sanitize(header.clang_version),
            sanitize(header.target),
        );
        // The annotations change the output, so it records them to be regenerated.
        let options: Vec<String> = self
            .buffers
            .iter()
            .map(|buffer| {
                format!(
                    "--buffer {}:{}:{}",
                    buffer.function, buffer.pointer, buffer.length
                )
            })
            .chain(
                self.consumes
                    .iter()
                    .map(|consume| format!("--consume {}:{}", consume.function, consume.parameter)),
            )
            .collect();
        if !options.is_empty() {
            text.push_str(&format!("// options: {}\n", sanitize(&options.join(" "))));
        }
        if !self.lines.is_empty() {
            text.push('\n');
            for line in &self.lines {
                text.push_str(line);
                text.push('\n');
            }
        }
        Generated {
            text,
            skipped: self.skipped,
        }
    }
}

/// The one place that spells an E12 link-named extern declaration.
fn render_function(symbol: &str, name: &str, parameters: &[String], result: &str) -> String {
    let mut signature: Vec<&str> = if parameters.is_empty() {
        vec!["unit"]
    } else {
        parameters.iter().map(String::as_str).collect()
    };
    signature.push(result);
    format!(
        "extern \"{symbol}\" def {name} :: {}",
        signature.join(" -> ")
    )
}

#[cfg(test)]
mod tests {
    use super::*;

    fn parsed(text: &str) -> CType {
        parse_type(text).map_or(CType::Unsupported, |(ty, _)| ty)
    }

    #[test]
    fn parses_clang_type_spellings() {
        let named = |name: &str| CType::Named(name.into());
        let constant = Qualifiers {
            constant: true,
            volatile: false,
        };
        assert_eq!(parsed("unsigned long"), named("unsigned long"));
        assert_eq!(parse_type("const int"), Some((named("int"), constant)));
        assert_eq!(
            parsed("const struct point *const"),
            CType::Pointer(Box::new(named("struct point")), constant)
        );
        assert_eq!(
            parsed("int * _Nonnull"),
            CType::Pointer(Box::new(named("int")), Qualifiers::default())
        );
        assert_eq!(
            parsed("int (*)(int, const char *)"),
            CType::Pointer(
                Box::new(CType::Function(
                    Box::new(named("int")),
                    vec![
                        named("int"),
                        CType::Pointer(Box::new(named("char")), constant)
                    ]
                )),
                Qualifiers::default()
            )
        );
        for unsupported in [
            "int (^)(int)",
            "int [4]",
            "struct (unnamed struct at /h/a.h:1:1)",
            "__attribute__((__vector_size__(4 * sizeof(int)))) int",
            "typeof (sizeof (0))",
        ] {
            assert!(parse_type(unsupported).is_none(), "{unsupported}");
        }
        assert_eq!(
            parsed("int (*)(int, ...)"),
            CType::Pointer(Box::new(CType::Unsupported), Qualifiers::default())
        );
    }

    #[test]
    fn splits_function_types() {
        let shape = function_shape("struct opaque *(void)").unwrap();
        assert_eq!(shape.result, Ok("struct opaque *".into()));
        assert!(shape.prototype && shape.attributes.is_empty());
        let shape = function_shape("void (int) __attribute__((noreturn))").unwrap();
        assert_eq!(shape.attributes, ["noreturn"]);
        let shape = function_shape("__attribute__((preserve_most)) int (int)").unwrap();
        assert_eq!(shape.result, Ok("int".into()));
        assert_eq!(shape.attributes, ["preserve_most"]);
        assert!(!function_shape("int ()").unwrap().prototype);
        assert_eq!(
            function_shape("int (*(int))(void)").unwrap().result,
            Err("int (*)(void)".into())
        );
        let anonymous = function_shape("struct (unnamed struct at /h/a.h:1:1) (void)").unwrap();
        assert_eq!(
            anonymous.result,
            Ok("struct (unnamed struct at /h/a.h:1:1)".into())
        );
        assert_eq!(
            scrub("struct (unnamed struct at /h/a.h:1:1) *"),
            "struct (unnamed struct) *"
        );
    }

    #[test]
    fn converts_enum_initializer_values_like_c() {
        assert_eq!(convert(4294967295, "int"), Some(-1));
        assert_eq!(convert(-1, "unsigned int"), Some(4294967295));
        assert_eq!(convert(5, "long double"), None);
    }

    #[test]
    fn reads_line_markers_and_lines_like_clang() {
        assert_eq!(
            linemarker("# 3 \"/h/a\\\\b\\\"c\\303\\251\\t.h\" 2 3"),
            Some((3, b"/h/a\\b\"c\xc3\xa9\t.h".to_vec()))
        );
        assert_eq!(
            linemarker("# 1 \"<built-in>\""),
            Some((1, b"<built-in>".to_vec()))
        );
        for other in [
            "#define X 1",
            "# x \"a\"",
            "#pragma once",
            "# 3 \"unterminated",
        ] {
            assert_eq!(linemarker(other), None, "{other}");
        }
        assert_eq!(line_starts(b"a\r\nb\nc\rd"), [0, 3, 5, 7]);
        let text = b"int a;\r\n  #  define  LIMIT 4\n";
        assert_eq!(
            macro_position(text, &line_starts(text), 2, "LIMIT"),
            (21, 5)
        );
        assert_eq!(macro_position(text, &line_starts(text), 9, "LIMIT"), (0, 0));
    }

    #[test]
    fn reads_only_single_integer_literals_from_macros() {
        assert_eq!(macro_value("(-(7))"), MacroValue::Integer(-7, Scalar::I32));
        assert_eq!(macro_value("-0u"), MacroValue::Integer(0, Scalar::I32u));
        assert_eq!(macro_value(".5"), MacroValue::NotInteger);
        assert_eq!(macro_value("1e+5"), MacroValue::NotInteger);
        assert_eq!(macro_value("0x1.8p1"), MacroValue::NotInteger);
        assert_eq!(macro_value("1 2"), MacroValue::NotInteger);
        assert_eq!(macro_value(""), MacroValue::NotInteger);
        assert_eq!(macro_value(&"(".repeat(100)), MacroValue::NotInteger);
    }
}
