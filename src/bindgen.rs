#[derive(Clone, Copy, Debug, PartialEq, Eq)]
enum Scalar {
    Bool,
    I8,
    I8u,
    I16,
    I16u,
    I32,
    I32u,
    I64,
    I64u,
    F32,
    F64,
}

impl Scalar {
    /// The C builtin types bindgen converts, spelled as Clang prints them. Plain
    /// `char` is not one of them: its signedness depends on the target.
    fn of(name: &str) -> Option<Self> {
        Some(match name {
            "_Bool" => Self::Bool,
            "signed char" => Self::I8,
            "unsigned char" => Self::I8u,
            "short" => Self::I16,
            "unsigned short" => Self::I16u,
            "int" => Self::I32,
            "unsigned int" => Self::I32u,
            // LP64: `long` is 64 bits.
            "long" | "long long" => Self::I64,
            "unsigned long" | "unsigned long long" => Self::I64u,
            "float" => Self::F32,
            "double" => Self::F64,
            _ => return None,
        })
    }

    fn name(self) -> &'static str {
        match self {
            Self::Bool => "bool",
            Self::I8 => "i8",
            Self::I8u => "i8u",
            Self::I16 => "i16",
            Self::I16u => "i16u",
            Self::I32 => "i32",
            Self::I32u => "i32u",
            Self::I64 => "i64",
            Self::I64u => "i64u",
            Self::F32 => "f32",
            Self::F64 => "f64",
        }
    }

    /// The Tsuzuri type in each position. A `_Bool` that C hands to Tsuzuri (an
    /// extern's result, a callback's parameter) becomes `i8u` because C guarantees only
    /// its low 8 bits, while a Tsuzuri `bool` reads all 32 bits of the ABI value. ABI
    /// records widen `bool` and narrow integers to 32 bits, so fields take only 32- and
    /// 64-bit scalars, which C lays out the same way.
    fn in_role(self, role: Role) -> Option<&'static str> {
        match (self, role) {
            (Self::Bool, Role::Result | Role::CallbackParameter) => Some("i8u"),
            (Self::Bool | Self::I8 | Self::I8u | Self::I16 | Self::I16u, Role::Field) => None,
            _ => Some(self.name()),
        }
    }
}

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
enum Role {
    Parameter,
    Result,
    Field,
    /// A parameter of a function pointer parameter: C passes it to Tsuzuri.
    CallbackParameter,
    /// The result of a function pointer parameter: Tsuzuri returns it to C.
    CallbackResult,
}

struct Typedef<'a> {
    spelled: &'a str,
    desugared: Option<&'a str>,
    /// An alignment or packing attribute changes the type's layout, which its
    /// spelling does not show.
    poisoned: bool,
}

struct Tables<'a> {
    typedefs: BTreeMap<&'a str, Typedef<'a>>,
    /// `enum TAG` (or `enum NAME` for an anonymous enum named by a typedef) → whether
    /// the enum is an `int`: every constant fits in i32, with no fixed underlying type
    /// and no packing.
    enums: BTreeMap<String, bool>,
    /// Anonymous struct, union, and enum declarations by id → the typedef that names
    /// them and where that name is.
    anonymous: BTreeMap<&'a str, (&'a str, (usize, usize))>,
    /// The ids of the implicit declarations Clang makes for library builtins.
    builtins: BTreeSet<&'a str>,
    /// Struct tags declared at file scope that no declaration of the translation unit
    /// defines: only pointers to them can exist, so they are opaque handles.
    incomplete: BTreeSet<&'a str>,
}

/// The tags of every struct definition, at any depth.
fn complete_structs<'a>(node: &'a Value, found: &mut BTreeSet<&'a str>, depth: usize) {
    if kind(node) == "RecordDecl"
        && flag(node, "completeDefinition")
        && text(node, "tagUsed") == Some("struct")
    {
        found.insert(name(node));
    }
    // serde_json limits nesting to 128.
    if depth < 128 {
        for child in children(node) {
            complete_structs(child, found, depth + 1);
        }
    }
}

impl<'a> Tables<'a> {
    fn new(nodes: &'a [Value]) -> Self {
        let mut complete = BTreeSet::new();
        for node in nodes {
            complete_structs(node, &mut complete, 0);
        }
        let mut tables = Self {
            typedefs: BTreeMap::new(),
            enums: BTreeMap::new(),
            anonymous: BTreeMap::new(),
            builtins: nodes
                .iter()
                .filter(|node| kind(node) == "FunctionDecl" && flag(node, "isImplicit"))
                .filter_map(|node| text(node, "id"))
                .collect(),
            incomplete: nodes
                .iter()
                .filter(|node| {
                    kind(node) == "RecordDecl" && text(node, "tagUsed") == Some("struct")
                })
                .map(name)
                .filter(|tag| !tag.is_empty() && !complete.contains(tag))
                .collect(),
        };
        for node in nodes.iter().filter(|node| kind(node) == "TypedefDecl") {
            let (spelled, desugared) = node_type(node);
            tables.typedefs.entry(name(node)).or_insert(Typedef {
                spelled,
                desugared,
                poisoned: has_attribute(node, LAYOUT_ATTRIBUTES),
            });
            let owned = children(node)
                .next()
                .and_then(|elaborated| elaborated.get("ownedTagDecl"));
            if let Some(tag) = owned
                && name(tag).is_empty()
                && let Some(id) = text(tag, "id")
            {
                tables
                    .anonymous
                    .entry(id)
                    .or_insert((name(node), position(node)));
            }
        }
        for node in nodes.iter().filter(|node| kind(node) == "EnumDecl") {
            let enumerators = tables.enumerators(node);
            // A forward declaration has no constants.
            let Some(key) = tables.enum_key(node).filter(|_| !enumerators.is_empty()) else {
                continue;
            };
            let int = node.get("fixedUnderlyingType").is_none()
                && !has_attribute(node, &["PackedAttr"])
                && enumerators.iter().all(|enumerator| {
                    enumerator
                        .value
                        .is_some_and(|value| i32::try_from(value).is_ok())
                });
            // Two enums spelled the same way (a tag and an anonymous enum's typedef)
            // are ambiguous, so neither converts.
            tables
                .enums
                .entry(key)
                .and_modify(|known| *known = false)
                .or_insert(int);
        }
        tables
    }

    fn enum_key(&self, node: &Value) -> Option<String> {
        let tag = match name(node) {
            "" => self.anonymous.get(text(node, "id")?)?.0,
            tag => tag,
        };
        Some(format!("enum {tag}"))
    }

    /// The constants of an enum with their values. C numbers a constant without an
    /// initializer as the previous one plus 1 (the first is 0); an initializer is a
    /// `ConstantExpr` with its value, maybe converted by an `ImplicitCastExpr` to the
    /// enumerator's type. Any other initializer leaves the value, and the values that
    /// follow from it, unknown.
    fn enumerators(&self, node: &'a Value) -> Vec<Enumerator<'a>> {
        let mut previous = Some(-1i128);
        let mut enumerators = Vec::new();
        for constant in children(node).filter(|child| kind(child) == "EnumConstantDecl") {
            let value = match children(constant).next() {
                None => previous.and_then(|value| value.checked_add(1)),
                Some(initializer) => self.constant_value(initializer, 0),
            };
            previous = value;
            enumerators.push(Enumerator {
                node: constant,
                value,
            });
        }
        enumerators
    }

    fn constant_value(&self, node: &Value, depth: usize) -> Option<i128> {
        match kind(node) {
            "ConstantExpr" => text(node, "value")?.parse().ok(),
            "ImplicitCastExpr"
                if depth < MAX_TYPE_NESTING
                    && matches!(text(node, "castKind"), Some("IntegralCast" | "NoOp")) =>
            {
                let value = self.constant_value(children(node).next()?, depth + 1)?;
                let (spelled, desugared) = node_type(node);
                let (ty, _) = self.c_type(spelled, desugared);
                let CType::Named(target) = ty else {
                    return None;
                };
                convert(value, &target)
            }
            _ => None,
        }
    }

    /// The type of a declaration with typedefs expanded: the spelling Clang printed,
    /// or its desugared spelling when this parser cannot read the printed one
    /// (`typeof`, for example).
    fn c_type(&self, spelled: &str, desugared: Option<&str>) -> (CType, Qualifiers) {
        let parsed = parse_type(spelled).or_else(|| desugared.and_then(parse_type));
        match parsed {
            Some((ty, qualifiers)) => self.resolve(ty, qualifiers, 0),
            None => (CType::Unsupported, Qualifiers::default()),
        }
    }

    /// Expands typedef names, at most `MAX_TYPEDEF_DEPTH` in a chain. The qualifiers of
    /// an expanded typedef join those of the place that names it.
    fn resolve(&self, ty: CType, qualifiers: Qualifiers, depth: usize) -> (CType, Qualifiers) {
        match ty {
            CType::Named(name) => match self.typedefs.get(name.as_str()) {
                None => (CType::Named(name), qualifiers),
                Some(typedef) if typedef.poisoned || depth >= MAX_TYPEDEF_DEPTH => {
                    (CType::Unsupported, qualifiers)
                }
                Some(typedef) => {
                    // An anonymous tag's typedef desugars to its own name.
                    let parsed = parse_type(typedef.spelled).or_else(|| {
                        typedef
                            .desugared
                            .filter(|desugared| *desugared != name)
                            .and_then(parse_type)
                    });
                    match parsed {
                        Some((inner, more)) => {
                            self.resolve(inner, qualifiers.union(more), depth + 1)
                        }
                        None => (CType::Unsupported, qualifiers),
                    }
                }
            },
            CType::Pointer(pointee, pointee_qualifiers) => {
                let (pointee, pointee_qualifiers) =
                    self.resolve(*pointee, pointee_qualifiers, depth);
                (
                    CType::Pointer(Box::new(pointee), pointee_qualifiers),
                    qualifiers,
                )
            }
            CType::Function(result, parameters) => {
                let result = self.resolve(*result, Qualifiers::default(), depth).0;
                let parameters = parameters
                    .into_iter()
                    .map(|parameter| self.resolve(parameter, Qualifiers::default(), depth).0)
                    .collect();
                (CType::Function(Box::new(result), parameters), qualifiers)
            }
            CType::Unsupported => (CType::Unsupported, qualifiers),
        }
    }

    /// The Tsuzuri scalar for a builtin or an `int` enum.
    fn scalar(&self, ty: &CType, role: Role) -> Option<&'static str> {
        let CType::Named(name) = ty else {
            return None;
        };
        if let Some(scalar) = Scalar::of(name) {
            return scalar.in_role(role);
        }
        (name.starts_with("enum ") && self.enums.get(name.as_str()) == Some(&true)).then_some("i32")
    }
}

struct Enumerator<'a> {
    node: &'a Value,
    value: Option<i128>,
}

/// C's conversion of an integer constant to an integer type (wrapping, as Clang does).
fn convert(value: i128, target: &str) -> Option<i128> {
    let (bits, signed) = match target {
        "signed char" => (8, true),
        "unsigned char" | "_Bool" => (8, false),
        "short" => (16, true),
        "unsigned short" => (16, false),
        "int" => (32, true),
        "unsigned int" => (32, false),
        "long" | "long long" => (64, true),
        "unsigned long" | "unsigned long long" => (64, false),
        _ => return None,
    };
    let modulus = 1i128 << bits;
    let wrapped = value.rem_euclid(modulus);
    Some(if signed && wrapped >= modulus / 2 {
        wrapped - modulus
    } else {
        wrapped
    })
}

