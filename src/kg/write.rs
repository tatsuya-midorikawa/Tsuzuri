//! Writing a knowledge graph's directory (G27 §2, §5, D-60): the files go to a staging directory
//! next to it, the marker last, and the staging directory replaces the old one by `rename`, so a
//! reader sees the old graph, no graph, or the new one, never a mixture. A directory without the
//! marker is never replaced.

use std::collections::BTreeMap;
use std::io;
use std::path::Path;

use crate::diagnostic::{Diagnostic, DiagnosticKind, Span};

/// The marker of a graph's directory: the first line names the writer, the second holds the
/// compiler's stamp, the third a token of this publication (no two publications share one).
pub const MARKER: &str = ".tsuzuri-kg";
const MARKER_LINE: &str = "generated by tsuzuri kg";
const MARKER_LIMIT: u64 = 4096;
pub const MANIFEST: &str = "manifest.json";
/// How often a write tries to replace a directory that another process replaces at once.
const ATTEMPTS: usize = 3;

/// The files of a graph by relative path (`/` separators).
#[derive(Clone, Debug, Default, PartialEq, Eq)]
pub struct Files(pub BTreeMap<String, Vec<u8>>);

impl Files {
    pub fn put(&mut self, path: impl Into<String>, bytes: Vec<u8>) {
        self.0.insert(path.into(), bytes);
    }

    pub fn get(&self, path: &str) -> Option<&[u8]> {
        self.0.get(path).map(Vec::as_slice)
    }
}

pub fn marker_text(stamp: &str) -> String {
    static PUBLICATIONS: std::sync::atomic::AtomicU64 = std::sync::atomic::AtomicU64::new(0);
    let nanos = std::time::SystemTime::now()
        .duration_since(std::time::UNIX_EPOCH)
        .map_or(0, |time| time.as_nanos());
    let count = PUBLICATIONS.fetch_add(1, std::sync::atomic::Ordering::Relaxed);
    format!(
        "{MARKER_LINE}\nstamp {stamp}\npublication {}-{nanos}-{count}\n",
        std::process::id()
    )
}

/// The text of the valid marker of `dir`: a regular file of at most 4,096 bytes whose first line
/// names the writer. Two reads that give the same text read one publication's marker.
pub fn read_marker(dir: &Path) -> Option<String> {
    let path = dir.join(MARKER);
    let metadata = std::fs::symlink_metadata(&path).ok()?;
    if !metadata.is_file() || metadata.len() > MARKER_LIMIT {
        return None;
    }
    let text = String::from_utf8(crate::cache::read_regular(&path, MARKER_LIMIT).ok()?).ok()?;
    (text.lines().next()? == MARKER_LINE).then_some(text)
}

/// The stamp in the text of a valid marker.
pub fn stamp_of(marker: &str) -> String {
    marker
        .lines()
        .nth(1)
        .and_then(|line| line.strip_prefix("stamp "))
        .unwrap_or("")
        .to_owned()
}

/// The stamp in the valid marker of `dir`.
pub fn marker_stamp(dir: &Path) -> Option<String> {
    read_marker(dir).map(|text| stamp_of(&text))
}

pub fn has_marker(dir: &Path) -> bool {
    marker_stamp(dir).is_some()
}

/// The most bytes of a stem: with a `~n` suffix and the longest extension (`.jsonl`), a file name
/// stays well under the 255 bytes of a name on common file systems.
pub const STEM_LIMIT: usize = 200;

/// The stem of a file name for a module key or a node ID: `::` becomes `.`, and every byte of a
/// character other than `[A-Za-z0-9_.]` becomes `%XX`. A stem longer than `STEM_LIMIT` bytes keeps
/// its first bytes (not cutting a `%XX`) and ends with `-` and the first 16 hexadecimal digits of
/// the ID's SHA-256, which no short stem contains.
pub fn stem(id: &str) -> String {
    let full = full_stem(id);
    if full.len() <= STEM_LIMIT {
        return full;
    }
    let digest = super::input::digest(id.as_bytes());
    let mut cut = STEM_LIMIT - 17;
    let bytes = full.as_bytes();
    if bytes[cut - 1] == b'%' {
        cut -= 1;
    } else if bytes[cut - 2] == b'%' {
        cut -= 2;
    }
    format!("{}-{}", &full[..cut], &digest[..16])
}

fn full_stem(id: &str) -> String {
    let mut out = String::new();
    for (index, part) in id.split("::").enumerate() {
        if index > 0 {
            out.push('.');
        }
        for character in part.chars() {
            if character.is_ascii_alphanumeric() || character == '_' || character == '.' {
                out.push(character);
            } else {
                let mut buffer = [0; 4];
                for byte in character.encode_utf8(&mut buffer).bytes() {
                    out.push_str(&format!("%{byte:02X}"));
                }
            }
        }
    }
    out
}

/// The stem of each ID in one directory: names that differ only in case get `~1`, `~2` after
/// the first in byte order, for file systems that ignore case.
pub fn unique_names(ids: &[String]) -> BTreeMap<String, String> {
    let mut sorted: Vec<&String> = ids.iter().collect();
    sorted.sort();
    sorted.dedup();
    let mut seen: BTreeMap<String, usize> = BTreeMap::new();
    let mut names = BTreeMap::new();
    for id in sorted {
        let stem = stem(id);
        let count = seen.entry(stem.to_lowercase()).or_insert(0);
        let name = if *count == 0 {
            stem
        } else {
            format!("{stem}~{count}")
        };
        *count += 1;
        names.insert(id.clone(), name);
    }
    names
}

fn io_failure(action: &str, path: &Path, error: io::Error) -> Diagnostic {
    Diagnostic::of(
        DiagnosticKind::IoFailure,
        format!("cannot {action} '{}': {error}", path.display()),
        Span::default(),
    )
}

/// `E2009` `kg_not_ours`: `dir` exists and is not a graph that the compiler wrote.
pub fn not_ours(dir: &Path) -> Diagnostic {
    Diagnostic::of(
        DiagnosticKind::KgNotOurs,
        format!(
            "'{}' exists and is not a KG (no {MARKER} marker); choose another directory with --kg-dir",
            dir.display()
        ),
        Span::default(),
    )
}

/// Removes `path` and everything below it, ignoring failures.
pub fn remove_tree(path: &Path) {
    let _ = std::fs::remove_dir_all(path);
}

/// Writes the files to a staging directory with the marker, in parallel, and puts it in place of
/// `output`. Returns how many files it wrote (the marker and `manifest.json` included).
pub fn publish(output: &Path, files: &Files, stamp: &str) -> Result<usize, Diagnostic> {
    let parent = match output.parent() {
        Some(parent) if !parent.as_os_str().is_empty() => parent.to_owned(),
        _ => std::path::PathBuf::from("."),
    };
    std::fs::create_dir_all(&parent)
        .map_err(|error| io_failure("create the KG directory", &parent, error))?;
    let temporary = crate::driver::TemporaryDirectory::new(&parent)?;
    let next = temporary.path.join("next");
    std::fs::create_dir(&next).map_err(|error| io_failure("create", &next, error))?;
    let mut directories: Vec<std::path::PathBuf> = files
        .0
        .keys()
        .filter_map(|path| Path::new(path).parent().map(|parent| next.join(parent)))
        .collect();
    directories.sort();
    directories.dedup();
    for directory in &directories {
        std::fs::create_dir_all(directory)
            .map_err(|error| io_failure("create", directory, error))?;
    }
    let entries: Vec<(&String, &Vec<u8>)> = files.0.iter().collect();
    let workers = crate::parallel::Parallelism::command_line().workers(entries.len(), 32);
    let failures: Vec<Option<Diagnostic>> = if workers < 2 {
        entries
            .iter()
            .map(|(path, bytes)| {
                let target = next.join(path);
                std::fs::write(&target, bytes)
                    .err()
                    .map(|error| io_failure("write", &target, error))
            })
            .collect()
    } else {
        let chunk = entries.len().div_ceil(workers);
        std::thread::scope(|scope| {
            let handles: Vec<_> = entries
                .chunks(chunk)
                .map(|part| {
                    let next = &next;
                    scope.spawn(move || {
                        part.iter()
                            .map(|(path, bytes)| {
                                let target = next.join(path);
                                std::fs::write(&target, bytes)
                                    .err()
                                    .map(|error| io_failure("write", &target, error))
                            })
                            .collect::<Vec<_>>()
                    })
                })
                .collect();
            handles
                .into_iter()
                .flat_map(|handle| handle.join().unwrap_or_default())
                .collect()
        })
    };
    if let Some(failure) = failures.into_iter().flatten().next() {
        return Err(failure);
    }
    let marker = next.join(MARKER);
    std::fs::write(&marker, marker_text(stamp))
        .map_err(|error| io_failure("write", &marker, error))?;
    for attempt in 0..ATTEMPTS {
        let previous = temporary.path.join(format!("previous-{attempt}"));
        let moved_away = match std::fs::symlink_metadata(output) {
            Err(error) if error.kind() == io::ErrorKind::NotFound => false,
            Ok(metadata) if metadata.is_dir() && has_marker(output) => {
                match std::fs::rename(output, &previous) {
                    Ok(()) => true,
                    Err(error) if error.kind() == io::ErrorKind::NotFound => false,
                    Err(error) => return Err(io_failure("replace", output, error)),
                }
            }
            _ => return Err(not_ours(output)),
        };
        match std::fs::rename(&next, output) {
            Ok(()) => {
                // The old graph and the staging directory go with the temporary directory.
                drop(temporary);
                return Ok(files.0.len() + 1);
            }
            Err(error)
                if matches!(
                    error.kind(),
                    io::ErrorKind::AlreadyExists
                        | io::ErrorKind::DirectoryNotEmpty
                        | io::ErrorKind::PermissionDenied
                ) =>
            {
                // Another process put its graph there first; try again.
                continue;
            }
            Err(error) => {
                if moved_away {
                    let _ = std::fs::rename(&previous, output);
                }
                return Err(io_failure("replace", output, error));
            }
        }
    }
    Err(Diagnostic::of(
        DiagnosticKind::IoFailure,
        format!("another process keeps replacing '{}'", output.display()),
        Span::default(),
    ))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn stems_escape_bytes_outside_the_safe_set() {
        assert_eq!(stem("Acme::Shop::Cart.total"), "Acme.Shop.Cart.total");
        assert_eq!(stem("Cart"), "Cart");
        assert_eq!(
            stem("instance:Add<Main.Point>.add"),
            "instance%3AAdd%3CMain.Point%3E.add"
        );
        assert_eq!(stem("test:Main.total adds"), "test%3AMain.total%20adds");
        assert_eq!(stem("é"), "%C3%A9");
    }

    #[test]
    fn long_stems_are_bounded_by_bytes() {
        let long = format!("Acme::{}.{}", "Module".repeat(40), "f");
        let bounded = stem(&long);
        assert_eq!(bounded.len(), STEM_LIMIT);
        let digest = crate::kg::input::digest(long.as_bytes());
        assert_eq!(
            bounded,
            format!("{}-{}", &full_stem(&long)[..183], &digest[..16])
        );
        // IDs that share their first bytes differ in their digests.
        let other = format!("Acme::{}.{}", "Module".repeat(40), "g");
        assert_ne!(stem(&other), bounded);
        // A `%XX` (`é` is `%C3%A9`) is not cut: the prefix ends before it or after it.
        let cut = |before: usize| {
            let id = format!("{}é{}", "a".repeat(before), "b".repeat(40));
            let bounded = stem(&id);
            bounded[..bounded.len() - 17].to_owned()
        };
        assert_eq!(cut(182), "a".repeat(182));
        assert_eq!(cut(181), "a".repeat(181));
        assert_eq!(cut(180), format!("{}%C3", "a".repeat(180)));
        let at_limit = "a".repeat(STEM_LIMIT);
        assert_eq!(stem(&at_limit), at_limit);
    }

    #[test]
    fn unique_names_separate_names_that_differ_only_in_case() {
        let ids = vec![
            "Main.b".to_owned(),
            "Main.B".to_owned(),
            "Main.c".to_owned(),
        ];
        let names = unique_names(&ids);
        assert_eq!(names["Main.B"], "Main.B");
        assert_eq!(names["Main.b"], "Main.b~1");
        assert_eq!(names["Main.c"], "Main.c");
    }

    #[test]
    fn publish_replaces_only_a_marked_directory() {
        let root = crate::driver::TemporaryDirectory::new(&std::env::temp_dir()).unwrap();
        let output = root.path.join("target/tz/kg");
        let mut files = Files::default();
        files.put("nodes.jsonl", b"{}\n".to_vec());
        files.put("facts/Main.jsonl", Vec::new());
        assert_eq!(publish(&output, &files, "00").unwrap(), 3);
        assert_eq!(marker_stamp(&output).as_deref(), Some("00"));
        assert!(output.join("facts/Main.jsonl").is_file());
        files.put("edges.jsonl", Vec::new());
        assert_eq!(publish(&output, &files, "11").unwrap(), 4);
        assert!(output.join("edges.jsonl").is_file());
        let leftovers: Vec<_> = std::fs::read_dir(output.parent().unwrap())
            .unwrap()
            .map(|entry| entry.unwrap().file_name())
            .filter(|name| name.to_string_lossy().starts_with(".tsuzuri-"))
            .collect();
        assert!(leftovers.is_empty(), "{leftovers:?}");
        let foreign = root.path.join("foreign");
        std::fs::create_dir_all(foreign.join("x")).unwrap();
        let error = publish(&foreign, &files, "22").unwrap_err();
        assert_eq!(error.code, "E2009");
        assert!(foreign.join("x").is_dir());
    }
}
